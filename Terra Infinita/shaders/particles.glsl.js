/* =============================================================================
 * TERRA INFINITA — GPU particle shaders (stateless: positions are a function of
 * instance id and time, so thousands of particles cost no CPU work)
 * Kinds: 0 rain, 1 snow, 2 dust/sand, 3 splashes, 4 fireflies, 5 leaves,
 *        6 embers/ash, 7 motes, 8 mist (waterfall/spray)
 * ========================================================================== */
(function () {
  'use strict';
  var S = TERRA.shaders;

  S.particleVS = [
    '#include <frame>',
    '#include <common>',
    '#include <wind>',
    '/* local gust relative to the mean wind: particles are carried by passing gust fronts */',
    'vec2 gustOffset(vec3 p){ return windField(p) - uWind.xy * uWind.z * 0.62; }',
    'uniform int uKind; uniform vec3 uBox; uniform float uIntensity; uniform float uCount;',
    'uniform sampler2D uHeightTex; uniform vec4 uField;',
    'uniform vec3 uEmitter;   // for localized emitters (mist)',
    'out vec2 vQ; out float vAlpha; out vec3 vCol; out float vLife; out float vDepthV; flat out int vK;',
    'vec3 wrapBox(vec3 seedPos, vec3 vel, float t){',
    '  vec3 p = seedPos * uBox + vel * t - uCamPos.xyz;',
    '  p = mod(p, uBox) - uBox * 0.5;',
    '  return uCamPos.xyz + p; }',
    'void main(){',
    '  int id = gl_InstanceID; int corner = gl_VertexID;',
    '  vec2 q = vec2(corner == 1 || corner == 2 ? 1.0 : -1.0, corner >= 2 ? 1.0 : -1.0);',
    '  vQ = q; vK = uKind;',
    '  float fid = float(id);',
    '  vec3 h = vec3(hash11(fid * 0.1031 + 0.37), hash11(fid * 0.2113 + 1.7), hash11(fid * 0.3571 + 5.1));',
    '  float h4 = hash11(fid * 0.719 + 9.3);',
    '  float t = uCamPos.w;',
    '  vec2 w = uWind.xy * uWind.z;',
    '  vec3 wp; vec3 right; vec3 up; float sx, sy;',
    '  vec3 toCam; vAlpha = 1.0; vCol = vec3(1.0); vLife = 1.0;',
    '  // fade out particles beyond intensity-controlled count',
    '  float alive = step(fid, uCount * uIntensity);',
    '  if (uKind == 0) {',
    '    vec3 vel = vec3(w.x * 9.0, -(8.5 + h4 * 2.5), w.y * 9.0);',
    '    wp = wrapBox(h, vel, t);',
    '    vec2 go = gustOffset(wp); vel.xz += go * 9.0; wp.xz += go * 1.2;',
    '    vec3 dir = normalize(vel);',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(dir, toCam));',
    '    up = dir;',
    '    sx = 0.006 + 0.004 * h.x; sy = 0.22 + 0.2 * h4;',
    '    float dist = length(uCamPos.xyz - wp);',
    '    vAlpha = alive * smoothstep(0.4, 1.5, dist) * (1.0 - smoothstep(uBox.x * 0.35, uBox.x * 0.5, dist)) * 0.35;',
    '  } else if (uKind == 9) {',
    '    // distant rain: long faint streaks in a large volume give heavy rain depth (curtains)',
    '    vec3 vel = vec3(w.x * 10.0, -(9.0 + h4 * 2.0), w.y * 10.0);',
    '    wp = wrapBox(h, vel, t);',
    '    vec2 go = gustOffset(wp); vel.xz += go * 10.0; wp.xz += go * 3.0;',
    '    vec3 dir = normalize(vel); toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(dir, toCam)); up = dir;',
    '    sx = 0.022 + 0.012 * h.x; sy = 1.4 + 1.2 * h4;',
    '    float dist = length(uCamPos.xyz - wp);',
    '    vAlpha = alive * smoothstep(10.0, 22.0, dist) * (1.0 - smoothstep(uBox.x * 0.33, uBox.x * 0.5, dist)) * 0.16;',
    '  } else if (uKind == 1) {',
    '    vec3 vel = vec3(w.x * 4.5, -(1.1 + h4 * 0.7), w.y * 4.5);',
    '    wp = wrapBox(h, vel, t);',
    '    wp += vec3(sin(t * (1.1 + h.x) + fid), 0.0, cos(t * (0.9 + h.y) + fid * 1.3)) * 0.25;',
    '    wp.xz += gustOffset(wp) * 2.6;',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(vec3(0.0, 1.0, 0.0), toCam)); up = cross(toCam, right);',
    '    sx = sy = 0.012 + 0.018 * h4;',
    '    float dist = length(uCamPos.xyz - wp);',
    '    vAlpha = alive * smoothstep(0.3, 1.0, dist) * (1.0 - smoothstep(uBox.x * 0.35, uBox.x * 0.5, dist)) * 0.85;',
    '  } else if (uKind == 2) {',
    '    vec3 vel = vec3(w.x * 14.0, sin(fid) * 0.5, w.y * 14.0);',
    '    wp = wrapBox(h, vel, t);',
    '    wp.xz += gustOffset(wp) * 6.0;',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(vec3(0.0, 1.0, 0.0), toCam)); up = cross(toCam, right);',
    '    sx = sy = 1.2 + 2.5 * h4;',
    '    float dist = length(uCamPos.xyz - wp);',
    '    vAlpha = alive * smoothstep(1.0, 4.0, dist) * (1.0 - smoothstep(uBox.x * 0.3, uBox.x * 0.5, dist)) * 0.07;',
    '    vCol = vec3(0.76, 0.6, 0.42);',
    '  } else if (uKind == 3) {',
    '    // rain splashes on the ground around the camera (world-stable grid)',
    '    float cellS = 0.9; float side = 36.0;',
    '    vec2 ij = vec2(mod(fid, side), floor(fid / side)) - side * 0.5;',
    '    vec2 cell = floor(uCamPos.xz / cellS) * cellS + ij * cellS;',
    '    vec2 r = hash22(cell * 0.37 + 11.0);',
    '    float period = 0.45 + r.x * 0.5;',
    '    float ph = fract(t / period + r.y);',
    '    vec2 cyc = hash22(cell + floor(t / period + r.y) * 3.17);',
    '    vec2 pos = cell + cyc * cellS;',
    '    vec2 fuv = (pos - uField.xy) * uField.w;',
    '    float gy = texture(uHeightTex, fuv).r;',
    '    wp = vec3(pos.x, gy + 0.02, pos.y);',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(vec3(0.0, 1.0, 0.0), toCam)); up = vec3(0.0, 1.0, 0.0);',
    '    sx = 0.05 + 0.1 * ph; sy = sx * 0.7;',
    '    wp.y += sy * 0.9;',
    '    vLife = ph;',
    '    float dist = length(uCamPos.xz - pos);',
    '    vAlpha = alive * (1.0 - ph) * (1.0 - smoothstep(10.0, 16.0, dist)) * 0.6 * step(hash12(cell + 7.7), uIntensity);',
    '  } else if (uKind == 4) {',
    '    // fireflies: wander near the ground',
    '    vec3 base = wrapBox(h, vec3(0.0), 0.0);',
    '    base.y = uCamPos.y - 1.2 + h.y * 2.5;',
    '    wp = base + vec3(sin(t * 0.3 + fid) * 1.5, sin(t * 0.7 + fid * 1.7) * 0.4, cos(t * 0.25 + fid * 0.9) * 1.5);',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(vec3(0.0, 1.0, 0.0), toCam)); up = cross(toCam, right);',
    '    sx = sy = 0.04;',
    '    float blink = smoothstep(0.6, 1.0, sin(t * (1.5 + h4) + fid * 7.0));',
    '    vAlpha = alive * blink; vCol = vec3(0.7, 1.0, 0.3) * 6.0;',
    '  } else if (uKind == 5) {',
    '    // falling leaves (tumbling)',
    '    vec3 vel = vec3(w.x * 2.5 + 0.3, -(0.8 + h4 * 0.6), w.y * 2.5);',
    '    wp = wrapBox(h, vel, t);',
    '    wp += vec3(sin(t * 1.7 + fid), 0.0, cos(t * 1.3 + fid)) * 0.6;',
    '    wp.xz += gustOffset(wp) * 3.2;',
    '    float a = t * (2.0 + h.x * 3.0) + fid;',
    '    right = vec3(cos(a), sin(a * 0.7) * 0.5, sin(a)); up = normalize(cross(right, vec3(sin(a * 1.3), 1.0, 0.2)));',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    sx = 0.05; sy = 0.035;',
    '    float dist = length(uCamPos.xyz - wp);',
    '    vAlpha = alive * (1.0 - smoothstep(uBox.x * 0.35, uBox.x * 0.5, dist));',
    '    vCol = mix(vec3(0.7, 0.3, 0.05), vec3(0.8, 0.6, 0.1), h.z);',
    '  } else if (uKind == 6) {',
    '    // embers / ash rising',
    '    vec3 vel = vec3(w.x * 3.0 + sin(fid) * 0.4, 1.2 + h4 * 1.5, w.y * 3.0 + cos(fid) * 0.4);',
    '    wp = wrapBox(h, vel, t);',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(vec3(0.0, 1.0, 0.0), toCam)); up = cross(toCam, right);',
    '    sx = sy = 0.02 + 0.03 * h4;',
    '    float glow = step(0.6, h.z);',
    '    vCol = mix(vec3(0.25, 0.24, 0.23), vec3(8.0, 2.5, 0.4), glow); vAlpha = alive * (glow > 0.5 ? 0.9 : 0.5);',
    '  } else {',
    '    // sunlit dust motes / waterfall mist',
    '    vec3 vel = vec3(sin(fid) * 0.1 + w.x, sin(t * 0.2 + fid) * 0.05, cos(fid) * 0.1 + w.y);',
    '    wp = wrapBox(h, vel, t);',
    '    toCam = normalize(uCamPos.xyz - wp);',
    '    right = normalize(cross(vec3(0.0, 1.0, 0.0), toCam)); up = cross(toCam, right);',
    '    sx = sy = uKind == 8 ? 0.8 + h4 * 1.5 : 0.01 + 0.01 * h4;',
    '    float dist = length(uCamPos.xyz - wp);',
    '    vAlpha = alive * (1.0 - smoothstep(uBox.x * 0.3, uBox.x * 0.5, dist)) * (uKind == 8 ? 0.08 : 0.8);',
    '  }',
    '  wp += right * q.x * sx + up * q.y * sy;',
    '  vec4 vp = uView * vec4(wp, 1.0); vDepthV = -vp.z;',
    '  gl_Position = uProj * vp;',
    '}'
  ].join('\n');

  S.particleFS = [
    '#include <frame>',
    '#include <common>',
    '#include <atmosphere>',
    'in vec2 vQ; in float vAlpha; in vec3 vCol; in float vLife; in float vDepthV; flat in int vK;',
    'out vec4 o;',
    'uniform sampler2D uDepth;',
    'void main(){',
    '  if (vAlpha <= 0.001) discard;',
    '  vec2 suv = gl_FragCoord.xy * uScreen.zw;',
    '  float sd = texture(uDepth, suv).r;',
    '  float sz = isSkyDepth(sd) ? 1e7 : linearDepth(sd);',
    '  float soft = saturate((sz - vDepthV) * (vK == 2 || vK == 8 ? 0.3 : 4.0));',
    '  if (soft <= 0.0) discard;',
    '  vec3 amb = texelFetch(uAmbientTex, ivec2(0, 0), 0).rgb / PI;',
    '  vec3 sunC = uSunColor.rgb;',
    '  float a = vAlpha * soft;',
    '  vec3 c;',
    '  float r2 = dot(vQ, vQ);',
    '  if (vK == 0 || vK == 9) {',
    '    float edge = 1.0 - abs(vQ.x); a *= edge * edge * smoothstep(1.0, 0.3, abs(vQ.y));',
    '    c = amb * 1.6 + sunC * 0.06 + vec3(0.8, 0.85, 1.0) * uWeather2.w * 2.0;',
    '  } else if (vK == 1) {',
    '    a *= smoothstep(1.0, 0.2, r2);',
    '    c = amb * 2.2 + sunC * 0.35 + vec3(1.0) * uWeather2.w;',
    '  } else if (vK == 2) {',
    '    a *= smoothstep(1.0, 0.0, r2);',
    '    c = vCol * (amb * 2.0 + sunC * 0.3);',
    '  } else if (vK == 3) {',
    '    float ring = smoothstep(0.25, 0.0, abs(sqrt(r2) - vLife * 0.9)) * step(0.0, vQ.y + 0.2);',
    '    float drops = smoothstep(0.2, 0.0, length(vQ - vec2(0.4, 0.5 * (1.0 - vLife)))) + smoothstep(0.2, 0.0, length(vQ - vec2(-0.5, 0.6 * (1.0 - vLife))));',
    '    a *= saturate(ring + drops);',
    '    c = amb * 2.0 + sunC * 0.1;',
    '  } else if (vK == 4 || vK == 6) {',
    '    a *= smoothstep(1.0, 0.0, r2);',
    '    c = vCol;',
    '  } else if (vK == 5) {',
    '    a *= smoothstep(1.0, 0.8, r2 * 1.1);',
    '    c = vCol * (amb * 1.2 + sunC * 0.25);',
    '  } else {',
    '    a *= smoothstep(1.0, 0.0, r2);',
    '    c = vK == 8 ? amb * 2.5 + sunC * 0.3 : sunC * 0.6 * saturate(dot(uSunDir.xyz, vec3(0.0, 1.0, 0.0)) * 4.0);',
    '  }',
    '  // fog on particles',
    '  float T = exp(-vDepthV * (uFog.x + 0.00002));',
    '  c = c * T + fogInscatter(normalize(vec3(0.0, 0.1, 1.0))) * (1.0 - T) * 0.0;',
    '  o = vec4(c * a, a);',
    '}'
  ].join('\n');

  /* Lightning bolt & bird silhouettes: simple coloured geometry */
  S.boltVS = [
    '#include <frame>',
    'layout(location = 0) in vec3 aPos; layout(location = 1) in float aW;',
    'out float vW;',
    'void main(){ vW = aW; gl_Position = uViewProj * vec4(aPos, 1.0); }'
  ].join('\n');
  S.boltFS = [
    'in float vW; out vec4 o; uniform float uAlpha; uniform vec3 uColor;',
    'void main(){ o = vec4(uColor * uAlpha, uAlpha); }'
  ].join('\n');
})();

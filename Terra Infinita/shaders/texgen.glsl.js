    '  float best = 1e3;',
    '  for (int i = 0; i < 17; i++) {',
    '    vec2 a, b; float lenF;',
    '    if (i == 0) { a = vec2(0.5, 0.0); b = vec2(0.5, 0.98); lenF = 1.0; }',
    '    else { float fi = float(i - 1); float side = mod(fi, 2.0) < 0.5 ? 1.0 : -1.0; float t = 0.08 + 0.85 * floor(fi / 2.0) / 7.0;',

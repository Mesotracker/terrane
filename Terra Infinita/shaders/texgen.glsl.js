    '  if (abs(y) > halfW) return;',
    '  h.cnt += 1.0;',
    '  if (z < h.z) return;',
    '  float ny = y / max(halfW, 1e-4);',
    '  float mid = smoothstep(0.09, 0.0, abs(ny)) * 0.25;',
    '  float lat = smoothstep(0.09, 0.0, abs(fract(u * 7.0 - abs(ny) * 0.8) - 0.5)) * 0.07 * (1.0 - abs(ny));',

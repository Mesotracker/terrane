    '}',
    'Hit newHit(){ Hit h; h.col = vec3(0.0); h.a = 0.0; h.n = vec3(0.0, 0.0, 1.0); h.tr = 0.0; h.z = -1.0; h.cnt = 0.0; return h; }',

    '    float along = s / length(b - a);',
    '    if (along < 0.0 || along > 1.05) continue;',
    '    float nl = 0.055 * (1.0 - along * 0.45) * (i == 0 ? 1.15 : 1.0);',
    '    if (abs(c) > nl) continue;',
    '    float ph = s * 95.0 - abs(c) * 32.0 + float(i) * 0.37;',

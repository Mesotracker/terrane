    '  // cracks',
    '  vec4 cv = voronoi(uv * 7.0 + fbm(uv, 4.0, 2, 0.5) * 0.3, 7.0, 1.0);',
    '  float crack = smoothstep(0.035, 0.0, cv.y - cv.x) * smoothstep(0.1, 0.4, n + 0.3);',
    '  m.h -= crack * 0.2; m.c *= 1.0 - crack * 0.4;',
    '  m.ao = 1.0; return m; }',
    'M rock(vec2 uv){',
    '  M m; float n = fbm(uv, 3.0, 7, 0.55); float r = ridgedF(uv, 4.0, 6);',
    '  float grain = fbm(uv, 64.0, 2, 0.5);',
    '  vec3 base = mix(vec3(0.36, 0.34, 0.32), vec3(0.55, 0.52, 0.48), n * 0.5 + 0.5);',
    '  base = mix(base, vec3(0.47, 0.42, 0.36), smoothstep(0.2, 0.6, fbm(uv + 7.7, 2.0, 3, 0.5)) * 0.6);',
    '  // mineral speckles',
    '  vec4 sp = voronoi(uv * 90.0, 90.0, 1.0);',
    '  float dark = smoothstep(0.25, 0.1, sp.x) * step(0.7, sp.z); float lite = smoothstep(0.2, 0.05, sp.x) * step(sp.z, 0.12);',
    '  base = mix(base, vec3(0.16, 0.15, 0.15), dark * 0.7); base = mix(base, vec3(0.78, 0.76, 0.72), lite * 0.6);',
    '  m.c = base * (0.9 + 0.2 * grain);',
    '  m.h = 0.3 + r * 0.45 + n * 0.15 + grain * 0.03;',
    '  // fractures',
    '  vec4 cv = voronoi(uv * 3.0 + vec2(fbm(uv, 3.0, 4, 0.5), fbm(uv + 1.7, 3.0, 4, 0.5)) * 0.7, 3.0, 1.0);',
    '  float crack = smoothstep(0.035, 0.0, cv.y - cv.x) * smoothstep(0.35, 0.6, fbm(uv + 9.1, 4.0, 3, 0.5) * 0.5 + 0.5);',
    '  vec4 cv2 = voronoi(uv * 13.0, 13.0, 1.0); float crack2 = smoothstep(0.025, 0.0, cv2.y - cv2.x) * 0.6;',
    '  m.h -= (crack * 0.6 + crack2) * 0.14; m.c *= 1.0 - (crack * 0.22 + crack2 * 0.15);',
    '  // lichen patches',
    '  float lich = smoothstep(0.55, 0.75, fbm(uv + 13.1, 8.0, 5, 0.6) * 0.5 + 0.5) * smoothstep(0.3, 0.6, m.h);',
    '  m.c = mix(m.c, mix(vec3(0.55, 0.56, 0.38), vec3(0.62, 0.52, 0.3), grain * 0.5 + 0.5), lich * 0.55);',
    '  m.r = 0.78 - lich * 0.05 + crack * 0.1; m.ao = 1.0; return m; }',
    'M cliff(vec2 uv){',
    '  M m; float warp = fbm(uv, 3.0, 4, 0.5); float warp2 = fbm(uv + 5.1, 7.0, 3, 0.5);',
    '  // few, irregular, strongly warped strata (5 per tile) so no regular stripes appear at distance',
    '  float y = uv.y * 5.0 + warp * 1.7 + warp2 * 0.35;',
    '  float band = fract(y); float bid = floor(y);',
    '  float bh = hash12(vec2(mod(bid, 5.0), 3.0) + uSeed);',
    '  vec3 c1 = vec3(0.56, 0.48, 0.38), c2 = vec3(0.50, 0.45, 0.40), c3 = vec3(0.61, 0.54, 0.44), c4 = vec3(0.47, 0.41, 0.34);',
    '  vec3 bc = bh < 0.25 ? c1 : (bh < 0.5 ? c2 : (bh < 0.75 ? c3 : c4));',
    '  float n = fbm(uv, 8.0, 5, 0.55);',
    '  // bands fade in and out along their length',
    '  float presence = smoothstep(0.2, 0.7, fbm(uv + 2.7, 4.0, 3, 0.5) * 0.5 + 0.5);',
    '  vec3 base = mix(vec3(0.53, 0.47, 0.40), bc, 0.35 + 0.5 * presence);',
    '  m.c = base * (0.85 + 0.25 * n);',
    '  float ledge = smoothstep(0.0, 0.2, band) * smoothstep(1.0, 0.75, band);',
    '  m.h = 0.3 + 0.3 * ledge * (0.5 + 0.5 * bh) * presence + n * 0.16;',
    '  vec4 cv = voronoi(vec2(uv.x * 7.0, uv.y * 3.0) + warp * 0.3, 7.0, 1.0);',
    '  float crack = smoothstep(0.05, 0.0, cv.y - cv.x); m.h -= crack * 0.22; m.c *= 1.0 - crack * 0.35;',
    '  m.c *= 1.0 - smoothstep(0.9, 1.0, band) * 0.1 * presence;',
    '  // weathering streaks running down the face',
    '  float streak = smoothstep(0.55, 0.8, fbm(vec2(uv.x * 4.0, uv.y), 6.0, 3, 0.5) * 0.5 + 0.5);',
    '  m.c *= 1.0 - streak * 0.12;',
    '  m.r = 0.85; m.ao = 1.0; return m; }',
    'M sand(vec2 uv){',
    '  M m; float n = fbm(uv, 4.0, 4, 0.5);',
    '  float ripple = sin((uv.y + fbm(uv, 3.0, 3, 0.5) * 0.12 + uv.x * 0.25) * TAU * 14.0) * 0.5 + 0.5;',
    '  float grain = hash12(floor(uv * 512.0) + uSeed) * 0.5 + fbm(uv, 128.0, 2, 0.5) * 0.5;',
    '  m.c = mix(vec3(0.76, 0.66, 0.50), vec3(0.84, 0.76, 0.60), n * 0.5 + 0.5) * (0.92 + 0.12 * grain);',

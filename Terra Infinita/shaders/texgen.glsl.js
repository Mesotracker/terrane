    '  // a side shoot adds depth',
    '  vec2 sb = stemPt(0.32, curve, lean), se = sb + vec2(kind == 1 ? -0.2 : 0.22, 0.26);',
    '  stem(h, p, sb, se, 0.007, 0.003, stemC, 0.01);',
    '  int NL = kind == 1 ? 22 : 15;',
    '  for (int i = 0; i < 22; i++) {',
    '    if (i >= NL) break;',
    '    float fi = float(i);',
    '    vec3 r = hash32(vec2(fi * 3.7 + 1.0, float(kind) * 11.0 + 2.0));',
    '    bool onSide = r.z < 0.25;',
    '    float t = 0.07 + 0.86 * fi / float(NL - 1);',

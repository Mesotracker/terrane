    'in vec2 vUv;',
    'uniform int uLayer;',
    'layout(location = 0) out vec4 oAlbedoH;',
    'layout(location = 1) out vec4 oRough;',
    'struct M { vec3 c; float h; float r; float ao; };',
    'M grass(vec2 uv, bool dry){',
    '  M m; float soil = fbm(uv, 6.0, 4, 0.55);',

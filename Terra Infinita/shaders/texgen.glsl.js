    '  float s = uStrength * float(uSize) / 512.0;',
    '  vec3 n = normalize(vec3((hl - hr) * s, (hd - hu) * s, 1.0));',
    '  float h = H(p); float avg = 0.0;',
    '  for (int y = -3; y <= 3; y += 2) for (int x = -3; x <= 3; x += 2) avg += H(p + ivec2(x, y) * max(1, uSize / 256));',

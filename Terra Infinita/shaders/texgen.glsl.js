    '    vec3 g = vec3(x, y, z); vec3 c = mod(i + g, per); vec3 r = g + hash33(c + uSeed) - f; d = min(d, dot(r, r)); }',
    '  return 1.0 - sqrt(d); }',
    'float gnoise3(vec3 p, float per){',

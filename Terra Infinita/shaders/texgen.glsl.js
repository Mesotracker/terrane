    '  m.c *= 0.94 + 0.08 * ripple;',
    '  vec4 v = voronoi(uv * 30.0, 30.0, 1.0); float peb = smoothstep(0.2, 0.08, v.x) * step(0.94, v.z);',
    '  m.c = mix(m.c, vec3(0.55, 0.5, 0.45) * (0.7 + 0.6 * v.z), peb); m.h += peb * 0.2;',
    '  m.r = 0.93; m.ao = 1.0; return m; }',
    'M snow(vec2 uv){',
    '  M m; float n = fbm(uv, 3.0, 5, 0.5); float s = fbm(uv + 4.4, 12.0, 3, 0.5);',
    '  float sast = sin((uv.x + n * 0.2) * TAU * 5.0) * 0.5 + 0.5;',
    '  m.c = vec3(0.90, 0.92, 0.95) * (0.95 + 0.05 * n); m.c = mix(m.c, vec3(0.82, 0.86, 0.93), smoothstep(0.1, -0.3, n) * 0.5);',
    '  m.h = 0.5 + n * 0.12 + s * 0.04 + sast * 0.05;',
    '  float sparkle = step(0.985, hash12(floor(uv * 700.0) + uSeed));',
    '  m.r = 0.55 - sparkle * 0.35 + s * 0.05; m.ao = 1.0; return m; }',
    'M gravel(vec2 uv){',
    '  M m; m.c = vec3(0.3, 0.29, 0.27); m.h = 0.1; m.r = 0.85;',
    '  for (int k = 0; k < 2; k++) {',
    '    float sc = k == 0 ? 14.0 : 26.0;',
    '    vec4 v = voronoi(uv * sc + float(k) * 0.37, sc, 0.9);',
    '    float stone = smoothstep(0.48, 0.2, v.x);',
    '    float hh = stone * (0.45 + 0.4 * v.z) * (k == 0 ? 1.0 : 0.8);',
    '    vec3 sc3 = mix(vec3(0.42, 0.40, 0.38), vec3(0.66, 0.62, 0.56), v.z) * (0.85 + 0.2 * hash12(vec2(v.z * 91.0, 3.0)));',
    '    if (v.z > 0.75) sc3 *= vec3(1.05, 0.92, 0.8);',
    '    if (hh > m.h) { m.h = hh; m.c = sc3 * (0.8 + 0.3 * (1.0 - v.x)); m.r = 0.7; }',
    '  }',
    '  m.ao = 1.0; return m; }',
    'M forest(vec2 uv){',
    '  M m; float n = fbm(uv, 5.0, 5, 0.55);',
    '  m.c = mix(vec3(0.17, 0.12, 0.08), vec3(0.27, 0.19, 0.12), n * 0.5 + 0.5); m.h = 0.15 + n * 0.1; m.r = 0.9;',
    '  // needles',
    '  vec4 nd = strokes(uv, 40.0, 1.6, 0.05, 1.0, 0.0, 3.0);',
    '  if (nd.x > 0.3) { m.c = mix(vec3(0.45, 0.32, 0.18), vec3(0.58, 0.42, 0.25), nd.z); m.h = max(m.h, 0.3 + nd.y * 0.15); }',

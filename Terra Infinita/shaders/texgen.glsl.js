    '  m.c = soilC; m.h = 0.15 + soil * 0.05; m.r = 0.95;',
    '  // stems/leaf litter underneath',
    '  vec4 s0 = strokes(uv, 36.0, 1.1, 0.09, 1.0, 0.0, 1.0);',
    '  vec3 litter = dry ? vec3(0.55, 0.47, 0.3) : vec3(0.38, 0.36, 0.2);',
    '  m.c = mix(m.c, litter * (0.8 + 0.3 * s0.z), s0.x * 0.7); m.h = max(m.h, 0.2 + s0.y * 0.2);',
    '  // three layers of blades, increasing height',
    '  for (int k = 0; k < 4; k++) {',
    '    float fk = float(k);',
    '    vec4 s = strokes(uv + fk * 0.137, 34.0 + fk * 11.0, 1.25 - fk * 0.15, 0.085 - fk * 0.01, 1.0, 0.0, 10.0 + fk * 7.0);',
    '    float hueVar = fbm(uv, 3.0, 3, 0.5) * 0.5 + 0.5;',
    '    vec3 g1 = dry ? vec3(0.62, 0.55, 0.32) : vec3(0.30, 0.42, 0.14);',
    '    vec3 g2 = dry ? vec3(0.74, 0.64, 0.38) : vec3(0.42, 0.52, 0.18);',
    '    vec3 g3 = dry ? vec3(0.52, 0.44, 0.26) : vec3(0.22, 0.34, 0.10);',
    '    vec3 bc = mix(mix(g3, g1, s.z), g2, hueVar * 0.6) * (0.86 + 0.24 * s.w);',
    '    if (!dry && s.z > 0.9) bc = mix(bc, vec3(0.6, 0.55, 0.3), 0.7);',
    '    float hh = 0.3 + fk * 0.15 + s.y * 0.3;',
    '    if (s.x > 0.3 && hh > m.h) { m.c = bc; m.h = hh; m.r = 0.72 + 0.15 * s.z; }',
    '  }',
    '  // tiny pebbles',
    '  vec4 v = voronoi(uv * 40.0, 40.0, 0.9);',
    '  float peb = smoothstep(0.26, 0.12, v.x) * step(0.93, v.z);',
    '  if (peb > 0.0 && m.h < 0.45) { m.c = mix(m.c, vec3(0.5, 0.48, 0.44) * (0.7 + 0.5 * v.z), peb); m.h = max(m.h, 0.3 * peb); }',
    '  m.ao = 1.0; return m; }',
    'M dirt(vec2 uv){',
    '  M m; float n = fbm(uv, 5.0, 6, 0.55); float n2 = fbm(uv + 3.3, 20.0, 4, 0.5);',
    '  m.c = mix(vec3(0.30, 0.23, 0.17), vec3(0.45, 0.36, 0.26), n * 0.5 + 0.5) * (0.9 + 0.2 * n2);',
    '  m.h = 0.35 + n * 0.15 + n2 * 0.06; m.r = 0.9;',
    '  vec4 v = voronoi(uv * 22.0, 22.0, 1.0);',
    '  float st = smoothstep(0.34, 0.1, v.x) * step(0.72, v.z);',
    '  m.c = mix(m.c, mix(vec3(0.42, 0.39, 0.35), vec3(0.58, 0.53, 0.46), v.z), st);',
    '  m.h += st * (0.35 - v.x * 0.6); m.r = mix(m.r, 0.75, st);',
    '  vec4 v2 = voronoi(uv * 60.0, 60.0, 1.0); float st2 = smoothstep(0.3, 0.1, v2.x) * step(0.6, v2.z);',

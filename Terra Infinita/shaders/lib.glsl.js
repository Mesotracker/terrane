/* =============================================================================
 * TERRA INFINITA — shared GLSL chunks (included with #include <name>)
 * ========================================================================== */
(function () {
  'use strict';
  var L = TERRA.shaders.lib = TERRA.shaders.lib || {};

  /* Per-frame uniform block (std140). Layout mirrored in renderer.js (FrameUBO). */
  L.frame = [
    'layout(std140) uniform Frame {',
    '  mat4 uView; mat4 uProj; mat4 uViewProj; mat4 uInvViewProj; mat4 uPrevViewProj; mat4 uInvView; mat4 uInvProj;',
    '  vec4 uCamPos;     // xyz camera (render space), w time (s)',
    '  vec4 uSunDir;     // xyz main light direction (sun or moon), w light intensity',
    '  vec4 uSunColor;   // rgb main light radiance, w day factor',
    '  vec4 uTrueSunDir; // xyz sun direction, w sun elevation (sin)',
    '  vec4 uMoonDir;    // xyz moon direction, w moon phase',
    '  vec4 uSkyAmb0;    // rgb zenith sky irradiance, w exposure',
    '  vec4 uSkyAmb1;    // rgb horizon sky irradiance, w ambient scale',
    '  vec4 uSkyAmb2;    // rgb ground bounce colour, w indirect strength',
    '  vec4 uFog;        // x density, y height falloff, z base height, w weather fog',
    '  vec4 uFogColor;   // rgb in-scatter tint, w mie strength',
    '  vec4 uWind;       // xy direction, z strength, w gust',
    '  vec4 uWeather;    // x wetness, y puddles, z snow cover, w rain',
    '  vec4 uWeather2;   // x snowfall, y cloud cover, z storm, w lightning flash',
    '  vec4 uScreen;     // w, h, 1/w, 1/h',
    '  vec4 uClip;       // near, far, season (0 spring .25 summer .5 autumn .75 winter), frame',
    '  vec4 uTexOrigin;  // xyz render origin mod 65536 (for >8 km periodic lookups), w sea level',
    '  vec4 uPlayer;     // xyz player feet (render space), w speed',
    '  vec4 uMisc;       // x debug view, y rtx, z micro detail, w dust/sandstorm',
    '  vec4 uTrail;      // xy trail map origin (render space xz), z trail size (m), w camera underwater',
    '  vec4 uMisc2;      // x temperature at camera, y aurora, z rainbow, w cloud shadow strength',
    '};'
  ].join('\n');

  L.common = [
    '#define PI 3.14159265359',
    '#define TAU 6.28318530718',
    'float saturate(float x){ return clamp(x, 0.0, 1.0); }',
    'vec2 saturate(vec2 x){ return clamp(x, 0.0, 1.0); }',
    'vec3 saturate(vec3 x){ return clamp(x, 0.0, 1.0); }',
    'float sq(float x){ return x * x; }',
    'float luma(vec3 c){ return dot(c, vec3(0.2126, 0.7152, 0.0722)); }',
    'float hash11(float p){ p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }',
    'float hash12(vec2 p){ vec3 p3 = fract(vec3(p.xyx) * 0.1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }',
    'vec2 hash22(vec2 p){ vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.xx + p3.yz) * p3.zy); }',
    'vec3 hash32(vec2 p){ vec3 p3 = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973)); p3 += dot(p3, p3.yxz + 33.33); return fract((p3.xxy + p3.yzz) * p3.zyx); }',
    'float hash13(vec3 p3){ p3 = fract(p3 * 0.1031); p3 += dot(p3, p3.zyx + 31.32); return fract((p3.x + p3.y) * p3.z); }',
    '// interleaved gradient noise (per pixel dither), animated with frame index',
    'float ign(vec2 px){ px += 5.588238 * mod(uClip.w, 64.0); return fract(52.9829189 * fract(dot(px, vec2(0.06711056, 0.00583715)))); }',
    'float vnoise(vec2 p){ vec2 i = floor(p), f = fract(p); vec2 u = f * f * (3.0 - 2.0 * f);',
    '  return mix(mix(hash12(i), hash12(i + vec2(1, 0)), u.x), mix(hash12(i + vec2(0, 1)), hash12(i + vec2(1, 1)), u.x), u.y); }',
    'float vnoise3(vec3 p){ vec3 i = floor(p), f = fract(p); vec3 u = f * f * (3.0 - 2.0 * f);',
    '  float a = hash13(i), b = hash13(i + vec3(1,0,0)), c = hash13(i + vec3(0,1,0)), d = hash13(i + vec3(1,1,0));',
    '  float e = hash13(i + vec3(0,0,1)), f1 = hash13(i + vec3(1,0,1)), g = hash13(i + vec3(0,1,1)), h = hash13(i + vec3(1,1,1));',
    '  return mix(mix(mix(a,b,u.x), mix(c,d,u.x), u.y), mix(mix(e,f1,u.x), mix(g,h,u.x), u.y), u.z); }',
    'float remap(float v, float a, float b, float c, float d){ return c + (v - a) / (b - a) * (d - c); }',
    'float linearDepth(float d){',
    '#ifdef REVERSED_Z',
    '  return uClip.x / max(d, 1e-8);',
    '#else',
    '  float z = d * 2.0 - 1.0; return 2.0 * uClip.x * uClip.y / (uClip.y + uClip.x - z * (uClip.y - uClip.x));',
    '#endif',
    '}',
    'bool isSkyDepth(float d){',
    '#ifdef REVERSED_Z',
    '  return d <= 0.0;',
    '#else',
    '  return d >= 1.0;',
    '#endif',
    '}',
    'vec3 viewPosFromDepth(vec2 uv, float d){',
    '#ifdef REVERSED_Z',
    '  vec4 c = vec4(uv * 2.0 - 1.0, d, 1.0);',
    '#else',
    '  vec4 c = vec4(uv * 2.0 - 1.0, d * 2.0 - 1.0, 1.0);',
    '#endif',
    '  vec4 v = uInvProj * c; return v.xyz / v.w; }',
    'vec3 viewRay(vec2 uv){ vec4 v = uInvProj * vec4(uv * 2.0 - 1.0, 0.5, 1.0); return normalize((uInvView * vec4(v.xyz / v.w, 0.0)).xyz); }',
    'vec2 projectToUV(vec3 renderPos){ vec4 c = uViewProj * vec4(renderPos, 1.0); return c.xy / c.w * 0.5 + 0.5; }',
    'float depthToNDC(float d){',
    '#ifdef REVERSED_Z',
    '  return d;',
    '#else',
    '  return d * 2.0 - 1.0;',
    '#endif',
    '}',
    '// Render origin is always a multiple of 8192 m, so textures with periods dividing 8192 m can use',
    '// render-space coordinates directly and stay continuous when the origin shifts.',
    'vec3 texPos(vec3 renderPos){ return renderPos; }',
    'float henyeyGreenstein(float c, float g){ float g2 = g * g; return (1.0 - g2) / (4.0 * PI * pow(1.0 + g2 - 2.0 * g * c, 1.5)); }'
  ].join('\n');

  /* Physically based shading helpers */
  L.pbr = [
    'float D_GGX(float NoH, float a){ float a2 = a * a; float f = (NoH * a2 - NoH) * NoH + 1.0; return a2 / (PI * f * f + 1e-7); }',
    'float V_SmithGGX(float NoV, float NoL, float a){ float a2 = a * a;',
    '  float gv = NoL * sqrt(NoV * NoV * (1.0 - a2) + a2); float gl = NoV * sqrt(NoL * NoL * (1.0 - a2) + a2); return 0.5 / max(gv + gl, 1e-5); }',
    'vec3 F_Schlick(vec3 f0, float VoH){ float f = pow(1.0 - VoH, 5.0); return f0 + (1.0 - f0) * f; }',
    'vec3 envBRDFApprox(vec3 f0, float rough, float NoV){',
    '  const vec4 c0 = vec4(-1.0, -0.0275, -0.572, 0.022); const vec4 c1 = vec4(1.0, 0.0425, 1.04, -0.04);',
    '  vec4 r = rough * c0 + c1; float a004 = min(r.x * r.x, exp2(-9.28 * NoV)) * r.x + r.y;',
    '  vec2 AB = vec2(-1.04, 1.04) * a004 + r.zw; return f0 * AB.x + AB.y; }',
    '/* Split-sum DFG terms (Karis analytic fit): x = scale, y = bias. */',
    'vec2 envBRDFAB(float rough, float NoV){',
    '  const vec4 c0 = vec4(-1.0, -0.0275, -0.572, 0.022); const vec4 c1 = vec4(1.0, 0.0425, 1.04, -0.04);',
    '  vec4 r = rough * c0 + c1; float a004 = min(r.x * r.x, exp2(-9.28 * NoV)) * r.x + r.y;',
    '  return vec2(-1.04, 1.04) * a004 + r.zw; }',
    '/* Multiple-scattering energy compensation for GGX (Fdez-Aguera 2019). */',
    'vec3 specEnergyComp(vec3 f0, vec2 AB){ float Ess = max(AB.x + AB.y, 1e-3); return 1.0 + f0 * (1.0 / Ess - 1.0); }',
    'float diffuseBurley(float NoV, float NoL, float LoH, float rough){',
    '  float f90 = 0.5 + 2.0 * rough * LoH * LoH;',
    '  float lS = 1.0 + (f90 - 1.0) * pow(1.0 - NoL, 5.0); float vS = 1.0 + (f90 - 1.0) * pow(1.0 - NoV, 5.0);',
    '  return lS * vS / PI; }',
    '/* Direct light with multi-scatter compensation and AO micro-shadowing (Chan 2018). */',
    'vec3 shadeDirectMS(vec3 N, vec3 V, vec3 L, vec3 albedo, float rough, float metal, float spec, float ao){',
    '  vec3 H = normalize(V + L); float NoL = saturate(dot(N, L)); float NoV = max(dot(N, V), 1e-4);',
    '  float NoH = saturate(dot(N, H)); float VoH = saturate(dot(V, H)); float LoH = saturate(dot(L, H));',
    '  float a = max(rough * rough, 0.002);',
    '  vec3 f0 = mix(vec3(0.04 * spec), albedo, metal);',
    '  vec3 F = F_Schlick(f0, VoH);',
    '  vec3 ec = specEnergyComp(f0, envBRDFAB(rough, NoV));',
    '  vec3 specular = D_GGX(NoH, a) * V_SmithGGX(NoV, NoL, a) * F * ec;',
    '  vec3 diffuse = (1.0 - F) * (1.0 - metal) * albedo * diffuseBurley(NoV, NoL, LoH, rough);',
    '  float micro = saturate(NoL + 2.0 * ao * ao - 1.0);',
    '  return (diffuse + specular) * NoL * micro; }',
    '/* Direct light BRDF. Returns radiance scale (multiply by light colour). */',
    'vec3 shadeDirect(vec3 N, vec3 V, vec3 L, vec3 albedo, float rough, float metal, float spec){',
    '  vec3 H = normalize(V + L); float NoL = saturate(dot(N, L)); float NoV = max(dot(N, V), 1e-4);',
    '  float NoH = saturate(dot(N, H)); float VoH = saturate(dot(V, H)); float LoH = saturate(dot(L, H));',
    '  float a = max(rough * rough, 0.002);',
    '  vec3 f0 = mix(vec3(0.04 * spec), albedo, metal);',
    '  vec3 F = F_Schlick(f0, VoH);',
    '  vec3 specular = D_GGX(NoH, a) * V_SmithGGX(NoV, NoL, a) * F;',
    '  vec3 diffuse = (1.0 - F) * (1.0 - metal) * albedo * diffuseBurley(NoV, NoL, LoH, rough);',
    '  return (diffuse + specular) * NoL; }'
  ].join('\n');

  /* Cascaded shadow maps */
  L.shadows = [
    'uniform highp sampler2DArrayShadow uShadowMap;',
    'uniform mat4 uShadowMat[4];',
    'uniform vec4 uShadowSplits;   // far distance of each cascade',
    'uniform vec4 uShadowParams;   // x texel size, y cascades, z softness, w enabled',
    'const vec2 POISSON[12] = vec2[](vec2(-0.326,-0.406), vec2(-0.840,-0.074), vec2(-0.696,0.457), vec2(-0.203,0.621),',
    '  vec2(0.962,-0.195), vec2(0.473,-0.480), vec2(0.519,0.767), vec2(0.185,-0.893), vec2(0.507,0.064), vec2(0.896,0.412), vec2(-0.322,-0.933), vec2(-0.792,-0.598));',
    'float shadowCascade(int ci, vec3 p, vec3 n, float rot){',
    '  float texel = uShadowParams.x * (ci == 0 ? 1.0 : (ci == 1 ? 2.6 : (ci == 2 ? 7.0 : 20.0)));',
    '  vec3 pp = p + n * texel * 1.6;',
    '  vec4 sc = uShadowMat[ci] * vec4(pp, 1.0); vec3 s = sc.xyz / sc.w;',
    '#ifndef REVERSED_Z',
    '  s.z = s.z * 0.5 + 0.5;',
    '#endif',
    '  s.xy = s.xy * 0.5 + 0.5;',
    '  if (any(lessThan(s.xy, vec2(0.0))) || any(greaterThan(s.xy, vec2(1.0))) || s.z > 1.0) return 1.0;',
    '  float bias = 0.00002 * (1.0 + float(ci) * 1.5);',
    '  float radius = uShadowParams.z * (ci == 0 ? 1.0 : 0.7) / (1.0 + float(ci) * 0.8);',
    '  float cs = cos(rot), sn = sin(rot); mat2 R = mat2(cs, sn, -sn, cs);',
    '  float sum = 0.0;',
    '  int taps = uShadowParams.z > 1.5 ? 12 : 6;',
    '  for (int i = 0; i < 12; i++) { if (i >= taps) break;',
    '    vec2 o = R * POISSON[i] * radius / 2048.0;',
    '    sum += texture(uShadowMap, vec4(s.xy + o, float(ci), s.z - bias)); }',
    '  return sum / float(taps); }',
    'float sampleShadow(vec3 p, vec3 n, float viewDist, vec2 fragCoord){',
    '  if (uShadowParams.w < 0.5) return 1.0;',
    '  float rot = ign(fragCoord) * TAU;',
    '  int cnt = int(uShadowParams.y);',
    '  for (int i = 0; i < 4; i++) {',
    '    if (i >= cnt) break;',
    '    float far = uShadowSplits[i];',
    '    if (viewDist < far) {',
    '      float s = shadowCascade(i, p, n, rot);',
    '      float blendZone = far * 0.85;',
    '      if (viewDist > blendZone && i + 1 < cnt) { float s2 = shadowCascade(i + 1, p, n, rot); s = mix(s, s2, saturate((viewDist - blendZone) / (far - blendZone))); }',
    '      else if (viewDist > blendZone) { s = mix(s, 1.0, saturate((viewDist - blendZone) / (far - blendZone))); }',
    '      return s; }',
    '  }',
    '  return 1.0; }'
  ].join('\n');

  /* Atmosphere: sky-view LUT lookup, sun/moon, aerial perspective */
  L.atmosphere = [
    'uniform sampler2D uSkyLUT;   // lat-long sky radiance (rgb) around the camera',
    'uniform sampler2D uAmbientTex; // 4x1: [0] zenith irr, [1] horizon irr, [2] sun transmittance, [3] fog colour',
    'vec2 skyUV(vec3 d){',
    '  float az = atan(d.z, d.x); float el = asin(clamp(d.y, -1.0, 1.0));',
    '  float v = 0.5 + 0.5 * sign(el) * sqrt(abs(el) / (PI * 0.5));',
    '  return vec2(az / TAU + 0.5, v); }',
    'vec3 skyRadiance(vec3 d){ return texture(uSkyLUT, skyUV(d)).rgb; }',
    'vec3 fogInscatter(vec3 dir){',
    '  vec3 d = normalize(vec3(dir.x, max(dir.y, 0.02) * 0.35 + 0.02, dir.z));',
    '  vec3 c = texture(uSkyLUT, skyUV(d)).rgb;',
    '  float mu = dot(dir, uTrueSunDir.xyz);',
    '  vec3 sunT = texelFetch(uAmbientTex, ivec2(2, 0), 0).rgb;',
    '  c += sunT * henyeyGreenstein(mu, 0.76) * uFogColor.w * 0.25 * saturate(uTrueSunDir.w * 6.0 + 0.2);',
    '  return c * uFogColor.rgb; }',
    '/* Exponential height fog, analytic integral along the ray. Returns transmittance; outputs in-scatter weight. */',
    'float fogTransmittance(vec3 camP, vec3 p){',
    '  vec3 d = p - camP; float dist = length(d);',
    '  float dens = uFog.x; float fall = uFog.y;',
    '  float h0 = camP.y - uFog.z; float dy = d.y;',
    '  float od;',
    '  if (abs(dy) > 0.01) od = dens * exp(-fall * h0) * (1.0 - exp(-fall * dy)) / (fall * dy) * dist;',
    '  else od = dens * exp(-fall * h0) * dist;',
    '  od += dist * 0.0000045;   // clean-air Rayleigh haze',
    '  return exp(-max(od, 0.0)); }'
  ].join('\n');

  /* G-buffer output layout */
  L.gbufferOut = [
    'layout(location = 0) out vec4 gAlbedo;   // rgb albedo (sRGB-ish), a material AO',
    'layout(location = 1) out vec4 gNormal;   // xyz world normal, a roughness',
    'layout(location = 2) out vec4 gMaterial; // r metallic, g wetness/water film, b translucency, a emissive'
  ].join('\n');

  /* Wind shared by vegetation, particles, water and the vegetation dynamics simulation.
   * Gusts are travelling fronts: low-frequency noise advected downwind at the wind speed,
   * stretched across the wind so they read as waves rolling over fields and forests.
   * Coordinates use world space (render space + origin) so gusts never jump. */
  L.wind = [
    'float gustAt(vec2 p, float t){',
    '  vec2 dir = uWind.xy; float s = uWind.z;',
    '  vec2 q = p - dir * t * (2.5 + 9.0 * s);',
    '  vec2 r = vec2(dot(q, dir), dot(q, vec2(-dir.y, dir.x)));',
    '  float g = vnoise(r * vec2(1.0 / 16.0, 1.0 / 44.0)) * 0.62 + vnoise(r * vec2(1.0 / 5.5, 1.0 / 13.0) + 7.3) * 0.38;',
    '  return smoothstep(0.3, 0.85, g); }',
    '/* Wind velocity (normalised strength units) at a render-space position. */',
    'vec2 windField(vec3 wp){',
    '  float t = uCamPos.w; vec2 dir = uWind.xy; float s = uWind.z;',
    '  vec2 p = wp.xz + uTexOrigin.xz;',
    '  float g = gustAt(p, t);',
    '  float turb = vnoise(p * 0.07 + vec2(t * 0.55, -t * 0.4)) - 0.5;',
    '  float k = s * (0.3 + 1.05 * g * (0.75 + 0.5 * uWind.w));',
    '  return dir * k + vec2(-dir.y, dir.x) * turb * s * 0.4; }',
    '/* Bend a vertex. `h` = height above the plant base, `stiff` = rigidity, `flutter` = leaf flutter weight.',
    '   Trunks respond to gusts with inertia (low-passed, delayed gust) and oscillate at their own',
    '   natural frequency with an amplitude that grows while a gust passes. */',
    'vec3 applyWind(vec3 wp, vec3 basePos, float h, float stiff, float flutter, float phase){',
    '  float t = uCamPos.w; vec2 dir = uWind.xy; float s = uWind.z;',
    '  vec2 bp = basePos.xz + uTexOrigin.xz;',
    '  float g = gustAt(bp, t - 0.35) * 0.6 + gustAt(bp, t - 0.95) * 0.4;',
    '  float natural = 1.6 + 0.9 * hash11(phase) + 2.0 / (1.0 + stiff * 0.2);',
    '  float osc = sin(t * natural + phase * 6.28);',
    '  float mean = s * (0.22 + 0.95 * g);',
    '  float sway = mean * (0.8 + 0.3 * osc * (0.35 + g)) + 0.025 * osc;',
    '  float bend = h * h / (stiff + 1e-3) * sway;',
    '  vec3 off = vec3(dir.x, 0.0, dir.y) * bend;',
    '  off.xz += vec2(-dir.y, dir.x) * sin(t * (natural * 1.37) + phase * 11.0) * bend * 0.22;',
    '  // leaf / needle flutter, stronger inside gusts',
    '  float fl = flutter * (0.02 + 0.11 * s * (0.4 + g));',
    '  off += vec3(sin(t * 9.0 + wp.x * 3.1 + phase * 30.0), sin(t * 11.0 + wp.y * 2.3 + phase * 17.0) * 0.6, cos(t * 8.0 + wp.z * 2.7)) * fl;',
    '  // keep length roughly constant (bend on an arc)',
    '  off.y -= dot(off.xz, off.xz) * 0.35 / max(h, 0.3);',
    '  return wp + off; }'
  ].join('\n');

  /* Tonemapping and grading helpers */
  L.tonemap = [
    'vec3 ACESFitted(vec3 color){',
    '  const mat3 ACESIn = mat3(0.59719, 0.07600, 0.02840, 0.35458, 0.90834, 0.13383, 0.04823, 0.01566, 0.83777);',
    '  const mat3 ACESOut = mat3(1.60475, -0.10208, -0.00327, -0.53108, 1.10813, -0.07276, -0.07367, -0.00605, 1.07602);',
    '  color = ACESIn * color;',
    '  vec3 a = color * (color + 0.0245786) - 0.000090537; vec3 b = color * (0.983729 * color + 0.4329510) + 0.238081;',
    '  color = a / b; return saturate(ACESOut * color); }',
    '/* AgX (Troy Sobotka; polynomial fit by B. Wrensch): camera-like highlight roll-off that',
    '   desaturates toward white instead of skewing hues — sunsets, skies and foliage stay natural.',
    '   Returns linear display-referred colour (same contract as ACESFitted). */',
    'vec3 agxContrast(vec3 x){ vec3 x2 = x * x, x4 = x2 * x2;',
    '  return 15.5 * x4 * x2 - 40.14 * x4 * x + 31.96 * x4 - 6.868 * x2 * x + 0.4298 * x2 + 0.1191 * x - 0.00232; }',
    'vec3 AgX(vec3 c){',
    '  const mat3 M = mat3(0.842479062253094, 0.0423282422610123, 0.0423756549057051, 0.0784335999999992, 0.878468636469772, 0.0784336, 0.0792237451477643, 0.0791661274605434, 0.879142973793104);',
    '  const mat3 Mi = mat3(1.19687900512017, -0.0528968517574562, -0.0529716355144438, -0.0980208811401368, 1.15190312990417, -0.0980434501171241, -0.0990297440797205, -0.0989611768448433, 1.15107367264116);',
    '  const float lo = -12.47393, hi = 4.026069;',
    '  c = M * max(c, vec3(1e-10));',
    '  c = (clamp(log2(c), lo, hi) - lo) / (hi - lo);',
    '  c = agxContrast(c);',
    '  // gentle "golden" look: a touch more contrast and saturation than base AgX',
    '  float l = dot(c, vec3(0.2126, 0.7152, 0.0722));',
    '  c = pow(max(c, 0.0), vec3(1.18)); l = dot(c, vec3(0.2126, 0.7152, 0.0722));',
    '  c = l + 1.18 * (c - l);',
    '  c = Mi * c;',
    '  return saturate(pow(max(c, 0.0), vec3(2.2))); }'
  ].join('\n');
})();

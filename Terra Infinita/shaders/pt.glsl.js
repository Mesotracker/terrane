/* =============================================================================
 * TERRA INFINITA — simulated path tracing (hybrid screen-space + height-field)
 * -----------------------------------------------------------------------------
 *  ptTraceFS    per pixel (half res): N cosine-weighted diffuse paths (1–16,
 *               stratified) + 1 GGX importance-sampled specular path. Rays march the
 *               depth buffer; rays leaving the screen continue through the 1 m terrain
 *               height field around the camera, then through the 12 km far field
 *               (world-space, shaded hits: albedo × sun × shadow + sky × visibility);
 *               misses gather sky radiance. Hit radiance is the
 *               previous lit frame (reprojected), so bounces accumulate over time
 *               (infinite-bounce GI, coloured bleeding, emissive light transport).
 *  ptTemporalFS reprojects and accumulates (up to 48 frames diffuse / 16 spec),
 *               rejecting history on disocclusion (depth test).
 *  ptAtrousFS   edge-aware à-trous wavelet filter (depth, normal, luminance).
 * ========================================================================== */
(function () {
  'use strict';
  var S = TERRA.shaders;

  S.ptTraceFS = [
    '#include <frame>',
    '#include <common>',
    '#include <atmosphere>',
    '#include <farfield>',
    '#include <farfieldTrace>',
    'in vec2 vUv;',
    'layout(location = 0) out vec4 oDiff;   // rgb incoming radiance (E/pi), a sky visibility',
    'layout(location = 1) out vec4 oSpec;   // rgb reflected radiance, a hit distance',
    'uniform sampler2D uDepth; uniform sampler2D uGNormal; uniform sampler2D uPrevHDR; uniform sampler2D uExposure; uniform sampler2D uGMat;',
    'uniform sampler2D uHeightTex; uniform vec4 uHField;   // xy origin (render space), z size, w enabled',
    'uniform int uSPP; uniform int uSteps; uniform float uFrameN;',
    'uniform vec3 uGroundBounce;',
    'vec2 rnd2(int k){',
    '  vec2 px = gl_FragCoord.xy;',
    '  vec2 a = vec2(ign(px + float(k) * vec2(17.0, 5.0)), ign(px.yx * 1.31 + float(k) * vec2(3.0, 23.0) + 11.0));',
    '  return fract(a + vec2(0.7548776662, 0.5698402910) * (uFrameN + float(k) * 13.0));',
    '}',
    '/* Stratified sample s of n: an R2 low-discrepancy set, rotated per pixel and per frame',
    '   (Cranley–Patterson), so 8 or 16 rays cover the hemisphere evenly instead of clumping. */',
    'vec2 rndS(int s, vec2 rot){ return fract(rot + vec2(0.7548776662, 0.5698402910) * float(s)); }',
    'vec3 cosineDir(vec3 N, vec2 r){',
    '  float phi = TAU * r.x; float ct = sqrt(1.0 - r.y), st = sqrt(r.y);',
    '  vec3 T = normalize(abs(N.y) < 0.99 ? cross(N, vec3(0.0, 1.0, 0.0)) : cross(N, vec3(1.0, 0.0, 0.0))); vec3 B = cross(N, T);',
    '  return normalize(T * cos(phi) * st + B * sin(phi) * st + N * ct); }',
    '/* GGX normal-distribution importance sample of the half vector. */',
    'vec3 ggxH(vec3 N, float a, vec2 r){',
    '  float phi = TAU * r.x; float ct = sqrt((1.0 - r.y) / (1.0 + (a * a - 1.0) * r.y)); float st = sqrt(1.0 - ct * ct);',
    '  vec3 T = normalize(abs(N.y) < 0.99 ? cross(N, vec3(0.0, 1.0, 0.0)) : cross(N, vec3(1.0, 0.0, 0.0))); vec3 B = cross(N, T);',
    '  return normalize(T * cos(phi) * st + B * sin(phi) * st + N * ct); }',
    '/* Screen-space march in view space. Returns (uv, state, distance): state 1 hit, 0 exhausted, 2 left screen. */',
    'vec4 ssTrace(vec3 vp, vec3 rv, float jit, int steps){',
    '  float dist = -vp.z;',
    '  float stepLen = 0.06 + dist * 0.008;',
    '  vec3 p = vp + rv * stepLen * (0.3 + jit);',
    '  for (int i = 0; i < 32; i++) {',
    '    if (i >= steps) break;',
    '    vec4 c = uProj * vec4(p, 1.0); if (c.w <= 0.0) return vec4(0.0, 0.0, 2.0, 0.0);',
    '    vec2 uv = c.xy / c.w * 0.5 + 0.5;',
    '    if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0)))) return vec4(uv, 2.0, length(p - vp));',
    '    float sdr = textureLod(uDepth, uv, 0.0).r;',
    '    if (!isSkyDepth(sdr)) {',
    '      float sd = linearDepth(sdr); float pz = -p.z;',
    '      // thin, translucent occluders (grass blades, leaf cards) only block within a few cm',
    '      float thick = textureLod(uGMat, uv, 0.0).b > 0.3 ? 0.06 + stepLen * 0.3 : max(0.6, stepLen * 2.5);',
    '      if (pz > sd + 0.02 && pz - sd < thick) return vec4(uv, 1.0, length(p - vp));',
    '    }',
    '    p += rv * stepLen; stepLen *= 1.22;',
    '  }',
    '  return vec4(0.0, 0.0, 0.0, 0.0); }',
    '/* World-space march against the local terrain height field (off-screen occluders). */',
    'float hfTrace(vec3 wp, vec3 dir, out vec3 hitP){',
    '  if (uHField.w < 0.5 || dir.y > 0.85) return 0.0;',
    '  float t = 0.6; hitP = wp;',
    '  for (int i = 0; i < 14; i++) {',
    '    vec3 p = wp + dir * t;',
    '    vec2 uv = (p.xz - uHField.xy) / uHField.z;',
    '    if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0)))) return 0.0;',
    '    float h = textureLod(uHeightTex, uv, 0.0).r;',
    '    if (p.y < h) { hitP = p; return 1.0; }',
    '    t += 0.5 + t * 0.35;',
    '    if (t > 90.0) break;',
    '  }',
    '  return 0.0; }',
    'vec3 gSkyE;',
    'vec3 radianceAtWorld(vec3 hw, float clampL){',
    '  vec4 pc = uPrevViewProj * vec4(hw, 1.0);',
    '  if (pc.w > 0.0) { vec2 puv = pc.xy / pc.w * 0.5 + 0.5;',
    '    if (all(greaterThan(puv, vec2(0.0))) && all(lessThan(puv, vec2(1.0)))) { vec3 L = texture(uPrevHDR, puv).rgb; float l = luma(L); return l > clampL ? L * clampL / l : L; } }',
    '  // off screen in the previous frame too: shade the hit from the far field (albedo, sun, shadow, sky)',
    '  if (uFF.w > 0.5) { vec2 fu = (hw.xz - uFF.xy) / uFF.z; if (all(greaterThan(fu, vec2(0.0))) && all(lessThan(fu, vec2(1.0)))) return ffRadiance(hw, gSkyE); }',
    '  return uGroundBounce; }',
    'vec3 skyL(vec3 d){ vec3 dd = normalize(vec3(d.x, max(d.y, 0.02), d.z)); return skyRadiance(dd) * uSkyAmb1.w; }',
    'void main(){',
    '  // checkerboard: each half-res pixel samples a different full-res sub-pixel every frame',
    '  ivec2 fp = ivec2(gl_FragCoord.xy) * 2 + ivec2(int(uFrameN) & 1, (int(uFrameN) >> 1) & 1);',
    '  fp = min(fp, textureSize(uDepth, 0) - 1);',
    '  float d = texelFetch(uDepth, fp, 0).r;',
    '  if (isSkyDepth(d)) { oDiff = vec4(0.0, 0.0, 0.0, 1.0); oSpec = vec4(0.0); return; }',
    '  vec2 uv = (vec2(fp) + 0.5) / vec2(textureSize(uDepth, 0));',
    '  vec4 gn = texelFetch(uGNormal, fp, 0);',
    '  vec3 N = normalize(gn.xyz); float rough = gn.w;',
    '  vec3 vp = viewPosFromDepth(uv, d);',
    '  vec3 wp = (uInvView * vec4(vp, 1.0)).xyz;',
    '  vec3 V = normalize(uCamPos.xyz - wp);',
    '  float e = texture(uExposure, vec2(0.5)).r; float clampL = 6.0 / max(e, 1e-4);',
    '  gSkyE = texelFetch(uAmbientTex, ivec2(0, 0), 0).rgb / PI * uSkyAmb1.w;',
    '  vec3 wpo = wp + N * (0.04 + length(vp) * 0.0015);',
    '  vec3 vpo = (uView * vec4(wpo, 1.0)).xyz;',
    '  // ---- diffuse paths',
    '  vec3 acc = vec3(0.0); float vis = 0.0;',
    '  vec2 rot = rnd2(0);',
    '  for (int s = 0; s < 16; s++) {',
    '    if (s >= uSPP) break;',
    '    vec2 r = uSPP > 1 ? rndS(s, rot) : rot;',
    '    vec3 dir = cosineDir(N, r);',
    '    vec3 rv = normalize((uView * vec4(dir, 0.0)).xyz);',
    '    vec4 h = ssTrace(vpo, rv, fract(r.x * 7.13 + r.y), uSteps);',
    '    vec3 L;',
    '    if (h.z == 1.0) {',
    '      float hd = textureLod(uDepth, h.xy, 0.0).r;',
    '      vec3 hv = viewPosFromDepth(h.xy, hd); vec3 hw = (uInvView * vec4(hv, 1.0)).xyz;',
    '      L = radianceAtWorld(hw, clampL);',
    '    } else {',
    '      vec3 hp;',
    '      if (hfTrace(wpo, dir, hp) > 0.5) L = radianceAtWorld(hp, clampL);',
    '      // world-space ray through the 12 km far field: valley walls, distant ridges',
    '      else if (ffTrace(wpo, dir, 60.0, hp) > 0.5) L = ffRadiance(hp, gSkyE);',
    '      else { L = skyL(dir); vis += 1.0; }',
    '    }',
    '    acc += L;',
    '  }',
    '  float n = float(max(uSPP, 1));',
    '  oDiff = vec4(acc / n, vis / n);',
    '  // ---- one specular path (GGX importance sampled)',
    '  vec3 spec = vec3(0.0); float sd = 0.0;',
    '  if (rough < 0.85) {',
    '    vec2 r = rnd2(7);',
    '    float a = max(rough * rough, 0.001);',
    '    vec3 H = ggxH(N, a, r);',
    '    vec3 R = reflect(-V, H);',
    '    if (dot(R, N) < 0.0) R = reflect(-V, N);',
    '    vec3 rv = normalize((uView * vec4(R, 0.0)).xyz);',
    '    vec4 h = ssTrace(vpo, rv, fract(r.y * 5.3 + r.x), uSteps + 8);',
    '    if (h.z == 1.0) {',
    '      float hd = textureLod(uDepth, h.xy, 0.0).r;',
    '      vec3 hv = viewPosFromDepth(h.xy, hd); vec3 hw = (uInvView * vec4(hv, 1.0)).xyz;',
    '      spec = radianceAtWorld(hw, clampL); sd = h.w;',
    '    } else {',
    '      vec3 hp;',
    '      if (hfTrace(wpo, R, hp) > 0.5) { spec = radianceAtWorld(hp, clampL); sd = distance(hp, wpo); }',
    '      else if (ffTrace(wpo, R, 60.0, hp) > 0.5) { spec = ffRadiance(hp, gSkyE); sd = distance(hp, wpo); }',
    '      else { spec = skyL(R); sd = 1000.0; }',
    '    }',
    '  }',
    '  oSpec = vec4(spec, sd);',
    '}'
  ].join('\n');

  S.ptTemporalFS = [
    '#include <frame>',
    '#include <common>',
    'in vec2 vUv;',
    'layout(location = 0) out vec4 oDiff;   // rgb accumulated, a history length',
    'layout(location = 1) out vec4 oSpec;   // rgb accumulated, a linear depth (for next frame\'s disocclusion test)',
    'uniform sampler2D uCurD; uniform sampler2D uCurS; uniform sampler2D uHistD; uniform sampler2D uHistS;',
    'uniform sampler2D uDepth; uniform mat4 uPrevVP; uniform float uReset; uniform float uMaxD; uniform float uMaxS;',
    'void main(){',
    '  vec4 cd = texture(uCurD, vUv), cs = texture(uCurS, vUv);',
    '  float d = textureLod(uDepth, vUv, 0.0).r;',
    '  if (isSkyDepth(d)) { oDiff = vec4(0.0); oSpec = vec4(0.0, 0.0, 0.0, 60000.0); return; }',
    '  vec3 vp = viewPosFromDepth(vUv, d);',
    '  float lin = -vp.z;',
    '  vec3 wp = (uInvView * vec4(vp, 1.0)).xyz;',
    '  vec4 pc = uPrevVP * vec4(wp, 1.0);',
    '  vec2 puv = pc.xy / pc.w * 0.5 + 0.5;',
    '  float histLen = 0.0; vec3 hd = cd.rgb, hs = cs.rgb;',
    '  if (uReset < 0.5 && pc.w > 0.0 && all(greaterThan(puv, vec2(0.0))) && all(lessThan(puv, vec2(1.0)))) {',
    '    vec4 H = texture(uHistD, puv), HS = texture(uHistS, puv);',
    '    // disocclusion: the stored depth must match where this point was last frame',
    '    float expect = pc.w;',
    '    if (abs(HS.a - expect) < expect * 0.06 + 0.1) { histLen = H.a; hd = H.rgb; hs = HS.rgb; }',
    '  }',
    '  float nD = min(histLen + 1.0, uMaxD), nS = min(histLen + 1.0, uMaxS);',
    '  vec3 accD = mix(hd, cd.rgb, 1.0 / nD);',
    '  vec3 accS = mix(hs, cs.rgb, 1.0 / nS);',
    '  oDiff = vec4(accD, nD);',
    '  oSpec = vec4(accS, lin);',
    '}'
  ].join('\n');

  /* Edge-aware à-trous (5×5 B3 spline taps at a growing step). a = history length passes through. */
  S.ptAtrousFS = [
    '#include <frame>',
    '#include <common>',
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uSrc; uniform sampler2D uDepth; uniform sampler2D uGNormal; uniform vec2 uTexel; uniform float uStep;',
    'void main(){',
    '  vec4 c0 = texture(uSrc, vUv);',
    '  float d0r = textureLod(uDepth, vUv, 0.0).r;',
    '  if (isSkyDepth(d0r)) { o = c0; return; }',
    '  float d0 = linearDepth(d0r); vec3 n0 = texture(uGNormal, vUv).xyz; float l0 = luma(c0.rgb);',
    '  float hist = max(c0.a, 1.0);',
    '  float sigL = 0.6 * (l0 + 0.03) * (1.0 + 6.0 / hist);',
    '  const float K[3] = float[](0.375, 0.25, 0.0625);',
    '  vec3 acc = vec3(0.0); float wsum = 0.0;',
    '  for (int j = -2; j <= 2; j++) for (int i = -2; i <= 2; i++) {',
    '    vec2 uv = vUv + vec2(i, j) * uTexel * uStep;',
    '    vec4 c = texture(uSrc, uv);',
    '    float dd = linearDepth(textureLod(uDepth, uv, 0.0).r);',
    '    vec3 nn = texture(uGNormal, uv).xyz;',
    '    float w = K[abs(i)] * K[abs(j)];',
    '    w *= exp(-abs(dd - d0) / (d0 * 0.02 * uStep + 0.05));',
    '    w *= pow(max(dot(nn, n0), 0.0), 24.0);',
    '    w *= exp(-abs(luma(c.rgb) - l0) / sigL);',
    '    acc += c.rgb * w; wsum += w;',
    '  }',
    '  o = vec4(acc / max(wsum, 1e-5), c0.a);',
    '}'
  ].join('\n');
})();

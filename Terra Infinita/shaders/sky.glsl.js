/* =============================================================================
 * TERRA INFINITA — atmosphere, sky and cloud shaders
 * ========================================================================== */
(function () {
  'use strict';
  var S = TERRA.shaders, L = S.lib;

  /* Physically based single scattering (Rayleigh + Mie + ozone). Units: metres. */
  L.atmoCore = [
    'const float R_PLANET = 6360e3; const float R_ATMO = 6460e3;',
    'const vec3 BETA_R = vec3(5.802e-6, 13.558e-6, 33.1e-6);',
    'const float BETA_M = 3.996e-6; const float BETA_M_EXT = 4.44e-6;',
    'const vec3 BETA_O = vec3(0.650e-6, 1.881e-6, 0.085e-6);',
    'const float H_R = 8000.0; const float H_M = 1200.0;',
    'uniform float uHaze;      // extra Mie turbidity (fog, dust, humidity)',
    'uniform vec3 uDustTint;',
    'vec2 raySphere(vec3 ro, vec3 rd, float r){ float b = dot(ro, rd); float c = dot(ro, ro) - r * r; float d = b * b - c; if (d < 0.0) return vec2(1e9, -1e9); d = sqrt(d); return vec2(-b - d, -b + d); }',
    'vec3 densities(float h){ h = max(h, 0.0); float o = max(0.0, 1.0 - abs(h - 25000.0) / 15000.0); return vec3(exp(-h / H_R), exp(-h / H_M) * (1.0 + uHaze), o); }',
    'vec3 extinction(vec3 d){ return BETA_R * d.x + vec3(BETA_M_EXT) * d.y * uDustTint + BETA_O * d.z; }',
    'vec3 transmittanceToSun(vec3 p, vec3 sunDir){',
    '  vec2 t = raySphere(p, sunDir, R_ATMO); float len = t.y; if (len <= 0.0) return vec3(1.0);',
    '  vec2 g = raySphere(p, sunDir, R_PLANET); if (g.x > 0.0) return vec3(0.0);',
    '  vec3 od = vec3(0.0); float st = len / 6.0;',
    '  for (int i = 0; i < 6; i++) { vec3 q = p + sunDir * (float(i) + 0.5) * st; od += densities(length(q) - R_PLANET) * st; }',
    '  return exp(-(BETA_R * od.x + vec3(BETA_M_EXT) * od.y * uDustTint + BETA_O * od.z)); }',
    'float phaseR(float mu){ return 3.0 / (16.0 * PI) * (1.0 + mu * mu); }',
    'float phaseM(float mu, float g){ float g2 = g * g; return 3.0 / (8.0 * PI) * ((1.0 - g2) * (1.0 + mu * mu)) / ((2.0 + g2) * pow(1.0 + g2 - 2.0 * g * mu, 1.5)); }',
    '/* In-scattered radiance along a view ray from altitude camH, for a light of intensity lightI. */',
    'vec3 scatter(float camH, vec3 rd, vec3 L, float lightI, int steps){',
    '  vec3 ro = vec3(0.0, R_PLANET + max(camH, 1.0), 0.0);',
    '  vec2 ta = raySphere(ro, rd, R_ATMO); float tmax = ta.y;',
    '  vec2 tg = raySphere(ro, rd, R_PLANET); if (tg.x > 0.0) tmax = min(tmax, tg.x);',
    '  float st = tmax / float(steps);',
    '  vec3 sumR = vec3(0.0), sumM = vec3(0.0), od = vec3(0.0);',
    '  float mu = dot(rd, L);',
    '  for (int i = 0; i < 24; i++) {',
    '    if (i >= steps) break;',
    '    float t = (float(i) + 0.5) * st; vec3 p = ro + rd * t; float h = length(p) - R_PLANET;',
    '    vec3 d = densities(h) * st; od += d;',
    '    vec3 Tv = exp(-(BETA_R * od.x + vec3(BETA_M_EXT) * od.y * uDustTint + BETA_O * od.z));',
    '    vec3 Ts = transmittanceToSun(p, L);',
    '    sumR += Tv * Ts * d.x; sumM += Tv * Ts * d.y;',
    '  }',
    '  vec3 single = lightI * (sumR * BETA_R * phaseR(mu) + sumM * BETA_M * uDustTint * phaseM(mu, 0.8));',
    '  // multiple-scattering approximation: isotropic, proportional to the scattering optical depth.',
    '  // Brightens and whitens the horizon like real skies (single scattering alone is too dark/orange).',
    '  vec3 ms = lightI * (sumR * BETA_R * vec3(0.98, 1.02, 1.08) + sumM * BETA_M * uDustTint * 0.3) * 0.12;',
    '  return single + ms;',
    '}'
  ].join('\n');

  /* Sky-view LUT: azimuth × (non-linear) elevation, HDR radiance. */
  S.skyLutFS = [
    '#include <frame>',
    '#include <common>',
    '#include <atmoCore>',
    'in vec2 vUv; out vec4 o;',
    'uniform float uCamAlt; uniform float uSunI; uniform float uMoonI;',
    'void main(){',
    '  float az = (vUv.x - 0.5) * TAU; float v = vUv.y * 2.0 - 1.0;',
    '  float el = sign(v) * v * v * PI * 0.5;',
    '  vec3 rd = vec3(cos(el) * cos(az), sin(el), cos(el) * sin(az));',
    '  vec3 c = scatter(uCamAlt, rd, uTrueSunDir.xyz, uSunI, 16);',
    '  c += scatter(uCamAlt, rd, uMoonDir.xyz, uMoonI, 8) * vec3(0.8, 0.9, 1.15);',
    '  // below horizon: blend towards a dim ground-reflected colour',
    '  if (el < 0.0) { c = mix(c, c * 0.5 + vec3(0.01, 0.012, 0.016) * uSunI * max(uTrueSunDir.y, 0.0), saturate(-el * 4.0)); }',
    '  o = vec4(c, 1.0);',
    '}'
  ].join('\n');

  /* 4×1 ambient: [0] upper-hemisphere irradiance, [1] horizon irradiance, [2] sun transmittance, [3] average horizon radiance */
  S.skyAmbientFS = [
    '#include <frame>',
    '#include <common>',
    '#include <atmoCore>',
    '#include <atmosphere>',
    'in vec2 vUv; out vec4 o;',
    'uniform float uCamAlt; uniform float uCloud; uniform float uStorm; uniform float uSunI; uniform float uMoonI;',
    'void main(){',
    '  int idx = int(gl_FragCoord.x);',
    '  vec3 res = vec3(0.0);',
    '  vec3 sunT = transmittanceToSun(vec3(0.0, R_PLANET + max(uCamAlt, 1.0), 0.0), uTrueSunDir.xyz) * uSunI;',
    '  vec3 moonT = transmittanceToSun(vec3(0.0, R_PLANET + max(uCamAlt, 1.0), 0.0), uMoonDir.xyz) * uMoonI * vec3(0.75, 0.85, 1.1);',
    '  // grey overcast sky radiance (light diffused by clouds)',
    '  vec3 overcast = (sunT * max(uTrueSunDir.y, 0.0) + moonT * max(uMoonDir.y, 0.0)) * 0.11 * (1.0 - uStorm * 0.65) + vec3(0.0006);',
    '  if (idx == 0 || idx == 1) {',
    '    vec3 acc = vec3(0.0); float wsum = 0.0;',
    '    for (int i = 0; i < 12; i++) for (int j = 0; j < 5; j++) {',
    '      float az = (float(i) + 0.5) / 12.0 * TAU; float el = (float(j) + 0.5) / 5.0 * PI * 0.5;',
    '      vec3 d = vec3(cos(el) * cos(az), sin(el), cos(el) * sin(az));',
    '      vec3 L = texture(uSkyLUT, skyUV(d)).rgb;',
    '      float w = idx == 0 ? sin(el) * cos(el) : cos(el) * cos(el) * max(cos(az), 0.0);',
    '      acc += L * w; wsum += w;',
    '    }',
    '    res = acc / wsum * PI;',
    '    if (idx == 1) res *= 0.5;',
    '    res = mix(res, overcast * PI * (idx == 0 ? 1.0 : 0.55), saturate(uCloud * 1.1 - 0.1));',
    '  } else if (idx == 2) {',
    '    res = (uTrueSunDir.y > -0.02 ? sunT : moonT);',
    '  } else {',
    '    vec3 acc = vec3(0.0);',
    '    for (int i = 0; i < 16; i++) { float az = (float(i) + 0.5) / 16.0 * TAU; acc += texture(uSkyLUT, skyUV(vec3(cos(az), 0.05, sin(az)))).rgb; }',
    '    res = mix(acc / 16.0, overcast * 1.2, saturate(uCloud * 1.1 - 0.1));',
    '  }',
    '  o = vec4(res, 1.0);',
    '}'
  ].join('\n');

  /* Cloud coverage in the weather layer (shared by clouds, cloud shadows, flat clouds) */
  L.cloudCommon = [
    'uniform sampler2D uNoiseTex2;',
    'uniform vec4 uCloudParams;   // x coverage, y base altitude, z thickness, w density',
    'uniform vec2 uCloudOffset;   // wind-advected offset (render space metres)',
    'float cloudCoverageAt(vec2 xz){',
    '  vec2 p = (xz + uCloudOffset + uTexOrigin.xz) / 16384.0;',
    '  vec4 n = texture(uNoiseTex2, p); vec4 n2 = texture(uNoiseTex2, p * 4.0 + 0.3);',
    '  float c = n.r * 0.65 + n2.g * 0.35;',
    '  float cov = uCloudParams.x;',
    '  return saturate(remap(c, 1.0 - cov * 1.05 - 0.05, 1.0, 0.0, 1.0) * 1.6); }'
  ].join('\n');

  /* Volumetric clouds (ray marched at reduced resolution). */
  S.cloudsFS = [
    '#include <frame>',
    '#include <common>',
    '#include <atmosphere>',
    '#include <cloudCommon>',
    'in vec2 vUv; out vec4 o;',
    'uniform highp sampler3D uCloudNoise;',
    'uniform sampler2D uDepth;',
    'uniform int uSteps; uniform int uLightSteps;',
    'float heightGradient(float hn){ return smoothstep(0.0, 0.12, hn) * smoothstep(1.0, 0.45, hn); }',
    'float cloudDensity(vec3 p, float cov, bool detail){',
    '  float base = uCloudParams.y, top = base + uCloudParams.z;',
    '  float hn = saturate((p.y - base) / (top - base));',
    '  vec3 q = (p + vec3(uCloudOffset.x, 0.0, uCloudOffset.y) + vec3(uTexOrigin.x, 0.0, uTexOrigin.z)) / 8192.0;',
    '  vec4 n = texture(uCloudNoise, q);',
    '  float shape = remap(n.r, -(1.0 - (n.g * 0.625 + n.b * 0.25 + n.a * 0.125)), 1.0, 0.0, 1.0);',
    '  shape *= heightGradient(hn) * (0.6 + 0.4 * hn);',
    '  float d = saturate(remap(shape, 1.0 - cov, 1.0, 0.0, 1.0));',
    '  if (detail && d > 0.0) { vec4 dn = texture(uCloudNoise, q * 4.0 + uCamPos.w * 0.002); float df = dn.g * 0.625 + dn.b * 0.25 + dn.a * 0.125; d = saturate(remap(d, df * 0.35 * (1.0 - hn * 0.5), 1.0, 0.0, 1.0)); }',
    '  return d * uCloudParams.w;',
    '}',
    'void main(){',
    '  vec3 rd = viewRay(vUv);',
    '  vec3 ro = uCamPos.xyz;',
    '  float base = uCloudParams.y, top = base + uCloudParams.z;',
    '  float t0, t1;',
    '  if (abs(rd.y) < 1e-4) { o = vec4(0.0, 0.0, 0.0, 1.0); return; }',
    '  float ta = (base - ro.y) / rd.y, tb = (top - ro.y) / rd.y;',
    '  t0 = max(min(ta, tb), 0.0); t1 = max(ta, tb);',
    '  float dScene = texture(uDepth, vUv).r;',
    '  float sceneDist = isSkyDepth(dScene) ? 1e9 : length(viewPosFromDepth(vUv, dScene));',
    '  t1 = min(t1, min(sceneDist, 60000.0));',
    '  if (t1 <= t0) { o = vec4(0.0, 0.0, 0.0, 1.0); return; }',
    '  int steps = uSteps;',
    '  float len = t1 - t0; float st = len / float(steps);',
    '  float jitter = ign(gl_FragCoord.xy);',
    '  vec3 L = uSunDir.xyz; float mu = dot(rd, uTrueSunDir.xyz);',
    '  float phase = mix(henyeyGreenstein(mu, 0.75), henyeyGreenstein(mu, -0.2), 0.3) * 4.0 * PI;',
    '  vec3 sunC = texelFetch(uAmbientTex, ivec2(2, 0), 0).rgb * (uTrueSunDir.y > -0.02 ? 1.0 : 1.0);',
    '  vec3 ambTop = texelFetch(uAmbientTex, ivec2(0, 0), 0).rgb / PI, ambBot = ambTop * 0.45 + texelFetch(uAmbientTex, ivec2(3, 0), 0).rgb * 0.2;',
    '  vec3 scat = vec3(0.0); float trans = 1.0;',
    '  float t = t0 + st * jitter;',
    '  float storm = uWeather2.z;',
    '  for (int i = 0; i < 96; i++) {',
    '    if (i >= steps || trans < 0.01) break;',
    '    vec3 p = ro + rd * t;',
    '    float cov = cloudCoverageAt(p.xz);',
    '    float dens = cloudDensity(p, cov, true);',
    '    if (dens > 0.001) {',
    '      // light march toward the sun',
    '      float od = 0.0; float ls = uCloudParams.z * 0.5 / float(uLightSteps);',
    '      for (int j = 0; j < 6; j++) { if (j >= uLightSteps) break; vec3 lp = p + L * ls * (float(j) + 0.5); od += cloudDensity(lp, cloudCoverageAt(lp.xz), false) * ls; }',
    '      float ext = 0.045;',
    '      float beer = exp(-od * ext) ;',
    '      float powder = 1.0 - exp(-od * ext * 2.0);',
    '      float hn = saturate((p.y - base) / (top - base));',
    '      vec3 direct = sunC * beer * mix(1.0, powder * 2.0, 0.5) * phase * uSunDir.w * 0.08;',
    '      vec3 amb = mix(ambBot, ambTop, hn) * (1.0 - storm * 0.6);',
    '      vec3 S = (direct + amb) * dens * (1.0 - storm * 0.55);',
    '      float sampleT = exp(-dens * ext * st);',
    '      scat += trans * (S - S * sampleT) / max(dens * ext, 1e-5);',
    '      trans *= sampleT;',
    '    }',
    '    t += st;',
    '  }',
    '  // lightning illuminates clouds from inside',
    '  scat += (1.0 - trans) * vec3(0.8, 0.85, 1.0) * uWeather2.w * 3.0;',
    '  // fade with distance (aerial perspective handled in composite)',
    '  float fade = exp(-t0 / 45000.0);',
    '  o = vec4(scat * fade, mix(1.0, trans, fade));',
    '}'
  ].join('\n');

  /* Sky colour for a direction (used by lighting pass for sky pixels & reflections). */
  L.skyColor = [
    'uniform sampler2D uCloudTex;  // volumetric clouds (rgb scatter, a transmittance)',
    'uniform int uCloudMode;       // 0 flat, 1 volumetric',
    'vec3 starField(vec3 d){',
    '  vec3 p = d * 320.0; vec3 i = floor(p); vec3 f = fract(p) - 0.5;',
    '  float h = hash13(i); float s = step(0.9925, h);',
    '  float tw = 0.65 + 0.35 * sin(uCamPos.w * (2.0 + h * 5.0) + h * 40.0);',
    '  float star = s * smoothstep(0.18, 0.0, length(f)) * tw * (h - 0.99) * 120.0;',
    '  vec3 col = mix(vec3(1.0, 0.8, 0.6), vec3(0.7, 0.8, 1.0), hash13(i + 3.0));',
    '  // faint milky way band',
    '  float band = exp(-pow(dot(d, normalize(vec3(0.3, 0.2, 1.0))) * 3.5, 2.0));',
    '  float mw = band * (vnoise3(d * 8.0) * 0.6 + vnoise3(d * 30.0) * 0.4);',
    '  return col * star + vec3(0.55, 0.6, 0.75) * mw * 0.012; }',
    'vec3 moonDisk(vec3 d){',
    '  vec3 m = uMoonDir.xyz; float c = dot(d, m); float r = 0.0095;',
    '  if (c < cos(r * 1.6)) return vec3(0.0);',
    '  vec3 up = abs(m.y) > 0.99 ? vec3(1, 0, 0) : vec3(0, 1, 0);',
    '  vec3 tx = normalize(cross(up, m)), ty = cross(m, tx);',
    '  vec2 q = vec2(dot(d, tx), dot(d, ty)) / r;',
    '  float rr = dot(q, q); if (rr > 1.0) return vec3(0.0);',
    '  vec3 n = vec3(q, sqrt(1.0 - rr));',
    '  float ph = uMoonDir.w * TAU; vec3 ls = normalize(vec3(sin(ph), 0.0, -cos(ph)));',
    '  float lit = smoothstep(-0.05, 0.1, dot(n, ls));',
    '  float mare = vnoise(q * 3.0 + 7.0) * 0.5 + vnoise(q * 9.0) * 0.25; float crater = smoothstep(0.62, 0.7, vnoise(q * 14.0));',
    '  vec3 alb = vec3(0.85, 0.84, 0.8) * (0.62 + 0.38 * (1.0 - mare)) * (1.0 - crater * 0.15);',
    '  return alb * lit * 1.2 + alb * 0.01; }',
    'vec3 aurora(vec3 d){',
    '  if (uMisc2.y < 0.01 || d.y < 0.02) return vec3(0.0);',
    '  vec3 acc = vec3(0.0);',
    '  for (int i = 0; i < 12; i++) {',
    '    float h = 0.12 + float(i) * 0.035;',
    '    vec2 p = d.xz / (d.y + 0.25) * (1.0 + float(i) * 0.05);',
    '    float n = vnoise(p * 1.6 + vec2(uCamPos.w * 0.03, 0.0)) ;',
    '    float curtain = smoothstep(0.35, 0.0, abs(sin(p.x * 1.3 + n * 3.0 + uCamPos.w * 0.05) - p.y * 0.2 - 0.3));',
    '    vec3 col = mix(vec3(0.1, 1.0, 0.45), vec3(0.6, 0.2, 1.0), float(i) / 12.0);',
    '    acc += col * curtain * n * smoothstep(0.0, 0.15, d.y) * (1.0 - float(i) / 12.0);',
    '  }',
    '  return acc * 0.012 * uMisc2.y; }',
    'vec3 rainbow(vec3 d){',
    '  if (uMisc2.z < 0.01) return vec3(0.0);',
    '  float a = acos(clamp(dot(d, -uTrueSunDir.xyz), -1.0, 1.0)) * 57.2958;',
    '  float t = (a - 40.4) / 2.4;',
    '  if (t < -0.2 || t > 1.2) return vec3(0.0);',
    '  vec3 c = saturate(vec3(1.5 - abs(4.0 * t - 3.6), 1.5 - abs(4.0 * t - 2.0), 1.5 - abs(4.0 * t - 0.4)));',
    '  return c * uMisc2.z * 0.35 * smoothstep(0.0, 0.1, d.y) * smoothstep(-0.2, 0.1, t) * smoothstep(1.2, 0.9, t); }',
    'vec3 flatClouds(vec3 d, vec3 skyC){',
    '  if (d.y < 0.01) return skyC;',
    '  float t = (uCloudParams.y + uCloudParams.z * 0.4 - uCamPos.y) / d.y;',
    '  vec3 p = uCamPos.xyz + d * t;',
    '  float cov = cloudCoverageAt(p.xz);',
    '  float n = texture(uNoiseTex2, (p.xz + uCloudOffset + uTexOrigin.xz) / 2048.0).a;',
    '  float c = saturate(cov * (0.6 + 0.8 * n));',
    '  vec3 sunC = texelFetch(uAmbientTex, ivec2(2, 0), 0).rgb * uSunDir.w;',
    '  vec3 amb = texelFetch(uAmbientTex, ivec2(0, 0), 0).rgb / PI;',
    '  float lightT = saturate(1.0 - c * 0.8);',
    '  vec3 cc = amb * 1.2 + sunC * (0.05 + 0.08 * lightT) * (1.0 + henyeyGreenstein(dot(d, uTrueSunDir.xyz), 0.6) * 3.0);',
    '  cc *= 1.0 - uWeather2.z * 0.6;',
    '  float fade = smoothstep(0.0, 0.12, d.y);',
    '  return mix(skyC, cc, c * fade * 0.95); }',
    'vec3 skyColorFull(vec3 d, vec2 uv, bool withSun){',
    '  vec3 c = skyRadiance(d);',
    '  float night = 1.0 - saturate(uTrueSunDir.w * 8.0 + 0.3);',
    '  // stars & moon are occluded by clouds',
    '  vec3 space = vec3(0.0);',
    '  if (night > 0.0 && d.y > -0.02) space += starField(d) * night;',
    '  space += moonDisk(d) * 0.35;',
    '  if (withSun) { float sd = dot(d, uTrueSunDir.xyz); float sunR = 0.99996; if (sd > sunR - 0.00002) {',
    '    float limb = saturate((sd - (sunR - 0.00002)) / 0.00004); vec3 sunT = texelFetch(uAmbientTex, ivec2(2, 0), 0).rgb;',
    '    space += sunT * 2500.0 * (0.55 + 0.45 * sqrt(limb)); } }',
    '  space += aurora(d);',
    '  float cloudT = 1.0;',
    '  if (uCloudMode == 1) {',
    '    vec4 cl = texture(uCloudTex, uv);',
    '    c = c * cl.a + cl.rgb; cloudT = cl.a;',
    '  } else {',
    '    vec3 before = c; c = flatClouds(d, c); cloudT = saturate(1.0 - length(c - before) / max(length(before), 1e-3));',
    '  }',
    '  c += space * cloudT;',
    '  c += rainbow(d) * luma(c) * 3.0;',
    '  // storm / overcast darkening and lightning sky flash',
    '  c *= 1.0 - uWeather2.z * 0.35;',
    '  c += vec3(0.6, 0.65, 0.8) * uWeather2.w * 0.6 * saturate(d.y + 0.3);',
    '  return c; }'
  ].join('\n');
})();

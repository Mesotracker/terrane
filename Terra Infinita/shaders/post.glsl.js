/* =============================================================================
 * TERRA INFINITA — deferred lighting & post-processing shaders
 * ========================================================================== */
(function () {
  'use strict';
  var S = TERRA.shaders;

  /* ---------------- SSAO + one-bounce screen-space GI (half resolution) ---------------- */
  S.ssaoFS = [
    '#include <frame>',
    '#include <common>',
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uDepth; uniform sampler2D uGNormal; uniform sampler2D uPrevHDR;',
    'uniform int uSamples; uniform int uGI; uniform float uIntensity;',
    'void main(){',
    '  float d = texture(uDepth, vUv).r;',
    '  if (isSkyDepth(d)) { o = vec4(0.0, 0.0, 0.0, 1.0); return; }',
    '  vec3 vp = viewPosFromDepth(vUv, d);',
    '  vec3 nw = texture(uGNormal, vUv).xyz;',
    '  vec3 nv = normalize((uView * vec4(nw, 0.0)).xyz);',
    '  float dist = -vp.z;',
    '  float radius = mix(0.6, 5.0, saturate(dist / 250.0));',
    '  float j = ign(gl_FragCoord.xy); float ja = j * TAU;',
    '  vec3 t = normalize(abs(nv.y) < 0.99 ? cross(nv, vec3(0.0, 1.0, 0.0)) : cross(nv, vec3(1.0, 0.0, 0.0)));',
    '  vec3 b = cross(nv, t);',
    '  float occ = 0.0; vec3 gi = vec3(0.0); float giw = 0.0;',
    '  for (int i = 0; i < 16; i++) {',
    '    if (i >= uSamples) break;',
    '    float fi = (float(i) + j) / float(uSamples);',
    '    float r = sqrt(fi); float a = ja + float(i) * 2.39996;',
    '    vec2 disk = vec2(cos(a), sin(a)) * r;',
    '    float h = sqrt(max(0.0, 1.0 - dot(disk, disk)));',
    '    vec3 sd = t * disk.x + b * disk.y + nv * h;',
    '    float len = radius * mix(0.15, 1.0, fi * fi);',
    '    vec3 sp = vp + sd * len;',
    '    vec4 c = uProj * vec4(sp, 1.0); vec2 suv = c.xy / c.w * 0.5 + 0.5;',
    '    if (any(lessThan(suv, vec2(0.0))) || any(greaterThan(suv, vec2(1.0)))) continue;',
    '    float sdz = linearDepth(texture(uDepth, suv).r);',
    '    float diff = -sp.z - sdz;',
    '    float range = smoothstep(0.0, 1.0, radius / max(abs(dist - sdz), 1e-3));',
    '    if (diff > 0.02) {',
    '      occ += range * h;',
    '      if (uGI == 1) { vec3 col = texture(uPrevHDR, suv).rgb; float w = range * h; gi += min(col, vec3(8.0)) * w; giw += w; }',
    '    }',
    '  }',
    '  float ao = 1.0 - occ / float(uSamples) * 1.6 * uIntensity;',
    '  ao = saturate(ao);',
    '  vec3 bounce = giw > 0.0 ? gi / float(uSamples) : vec3(0.0);',
    '  o = vec4(bounce, pow(ao, 1.3));',
    '}'
  ].join('\n');

  S.bilateralFS = [
    '#include <frame>',
    '#include <common>',
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uSrc; uniform sampler2D uDepth; uniform vec2 uDir;',
    'void main(){',
    '  float d0 = linearDepth(texture(uDepth, vUv).r);',
    '  vec4 acc = vec4(0.0); float wsum = 0.0;',
    '  for (int i = -4; i <= 4; i++) {',
    '    vec2 uv = vUv + uDir * float(i);',
    '    float di = linearDepth(texture(uDepth, uv).r);',
    '    float w = exp(-float(i * i) / 12.0) * exp(-abs(di - d0) / (d0 * 0.03 + 0.05));',
    '    acc += texture(uSrc, uv) * w; wsum += w;',
    '  }',
    '  o = acc / max(wsum, 1e-4);',
    '}'
  ].join('\n');

  /* ---------------- deferred lighting ---------------- */
  S.lightingFS = [
    '#include <frame>',
    '#include <common>',
    '#include <pbr>',
    '#include <shadows>',
    '#include <farfield>',
    '#include <atmosphere>',
    '#include <cloudCommon>',
    '#include <skyColor>',
    'in vec2 vUv; out vec4 oColor;',
    'uniform sampler2D uGAlbedo; uniform sampler2D uGNormal; uniform sampler2D uGMaterial; uniform sampler2D uDepth;',
    'uniform sampler2D uAOTex; uniform sampler2D uPrevHDR;',
    'uniform samplerCube uProbe;',
    'uniform vec4 uFeatures;   // x ssr quality, y gi, z contact shadows, w probe',
    'uniform vec4 uFeatures2;  // x ao enabled, y soft shadows, z underwater caustics, w -',
    'uniform vec4 uLightPos[8]; uniform vec4 uLightCol[8]; uniform int uNumLights;',
    'uniform vec4 uFlash;      // xyz direction, w intensity',
    'uniform sampler2D uPTDiff; uniform sampler2D uPTSpec; uniform vec4 uPT;   // x path tracing, y ray-traced sun shadows',
    'uniform sampler2D uHFTex; uniform vec4 uHField;',
    '/* Ray-traced soft sun shadow: one jittered ray inside the sun cone per pixel per frame',
    '   (TAA accumulates the penumbra). Screen-space march catches grass, leaves, rocks and',
    '   structures at full resolution; the terrain height field catches ridges off screen. */',
    'float rtSunShadow(vec3 wp, vec3 N, vec3 vp, vec3 L, vec2 fc, bool thin){',
    '  vec2 r = vec2(ign(fc), ign(fc.yx * 1.37 + 7.3));',
    '  vec3 T = normalize(cross(L, abs(L.y) < 0.99 ? vec3(0.0, 1.0, 0.0) : vec3(1.0, 0.0, 0.0))); vec3 B = cross(L, T);',
    '  vec2 disk = vec2(cos(r.x * TAU), sin(r.x * TAU)) * sqrt(r.y) * 0.014;',
    '  vec3 Ld = normalize(L + T * disk.x + B * disk.y);',
    '  vec3 Lv = normalize((uView * vec4(Ld, 0.0)).xyz);',
    '  vec3 Nv = normalize((uView * vec4(N, 0.0)).xyz);',
    '  float dist = -vp.z;',
    '  float st = 0.03 + dist * 0.0035;',
    '  vec3 p = vp + Nv * (0.02 + dist * 0.0015) + Lv * st * (0.5 + r.y);',
    '  // screen-space part: solid occluders only (grass blades and leaf cards are thinner than any',
    '  // depth-buffer thickness guess, so foliage pixels rely on shadow maps + the height field)',
    '  if (!thin) {',
    '    for (int i = 0; i < 22; i++) {',
    '      vec4 c = uProj * vec4(p, 1.0); if (c.w <= 0.0) break;',
    '      vec2 uv = c.xy / c.w * 0.5 + 0.5;',
    '      if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0)))) break;',
    '      float sdr = textureLod(uDepth, uv, 0.0).r;',
    '      if (!isSkyDepth(sdr)) {',
    '        float sd = linearDepth(sdr); float diff = -p.z - sd;',
    '        // the occluder must be solid (not a translucent blade/leaf) and plausibly thick',
    '        if (diff > 0.02 && diff < 0.12 + st * 1.2 && textureLod(uGMaterial, uv, 0.0).b < 0.3) return 0.0;',
    '      }',
    '      p += Lv * st; st *= 1.18;',
    '    }',
    '  }',
    '  if (uHField.w > 0.5) {',
    '    float t = 1.5;',
    '    for (int i = 0; i < 18; i++) {',
    '      vec3 q = wp + Ld * t; vec2 huv = (q.xz - uHField.xy) / uHField.z;',
    '      if (any(lessThan(huv, vec2(0.0))) || any(greaterThan(huv, vec2(1.0)))) break;',
    '      if (q.y < textureLod(uHFTex, huv, 0.0).r - 0.08) return 0.0;',
    '      t += 0.7 + t * 0.28; if (t > 140.0) break;',
    '    }',
    '  }',
    '  return 1.0; }',
    '/* Depth-aware 2x2 upsample of a half-resolution path-tracing buffer. */',
    'vec4 ptUpsample(sampler2D t, vec2 uv, float linD){',
    '  vec2 hs = vec2(textureSize(t, 0)); vec2 p = uv * hs - 0.5; vec2 f = fract(p); ivec2 b = ivec2(floor(p));',
    '  vec4 acc = vec4(0.0); float ws = 0.0;',
    '  for (int j = 0; j <= 1; j++) for (int i = 0; i <= 1; i++) {',
    '    ivec2 q = clamp(b + ivec2(i, j), ivec2(0), ivec2(hs) - 1); vec2 quv = (vec2(q) + 0.5) / hs;',
    '    float dq = linearDepth(textureLod(uDepth, quv, 0.0).r);',
    '    float w = (i == 0 ? 1.0 - f.x : f.x) * (j == 0 ? 1.0 - f.y : f.y) * exp(-abs(dq - linD) / (linD * 0.03 + 0.05)) + 1e-4;',
    '    acc += texelFetch(t, q, 0) * w; ws += w;',
    '  }',
    '  return acc / ws; }',
    'float contactShadow(vec3 vp, vec3 Lv, vec2 fc){',
    '  float len = clamp(-vp.z * 0.03, 0.25, 1.6); const int N = 12; float st = len / float(N);',
    '  vec3 p = vp + Lv * st * ign(fc);',
    '  for (int i = 0; i < N; i++) {',
    '    p += Lv * st;',
    '    vec4 c = uProj * vec4(p, 1.0); vec2 uv = c.xy / c.w * 0.5 + 0.5;',
    '    if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0)))) break;',
    '    float sd = linearDepth(textureLod(uDepth, uv, 0.0).r); float diff = -p.z - sd;',
    '    if (diff > 0.015 && diff < 0.6 && textureLod(uGMaterial, uv, 0.0).b < 0.3) return 0.0;   // thin foliage never casts contact shadows',
    '  }',
    '  return 1.0; }',
    'vec4 traceSSR(vec3 vp, vec3 rv, int steps, float jit){',
    '  float stepLen = 0.25 + (-vp.z) * 0.012;',
    '  vec3 p = vp + rv * stepLen * jit;',
    '  for (int i = 0; i < 64; i++) {',
    '    if (i >= steps) break;',
    '    p += rv * stepLen; stepLen *= 1.1;',
    '    vec4 c = uProj * vec4(p, 1.0); if (c.w <= 0.0) break;',
    '    vec2 uv = c.xy / c.w * 0.5 + 0.5;',
    '    if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0)))) break;',
    '    float sd = linearDepth(textureLod(uDepth, uv, 0.0).r); float pz = -p.z;',
    '    if (pz > sd && pz - sd < max(0.5, stepLen * 2.5)) {',
    '      vec3 a = p - rv * stepLen, b = p;',
    '      for (int k = 0; k < 5; k++) { vec3 m = (a + b) * 0.5; vec4 cm = uProj * vec4(m, 1.0); vec2 um = cm.xy / cm.w * 0.5 + 0.5;',
    '        if (-m.z > linearDepth(textureLod(uDepth, um, 0.0).r)) b = m; else a = m; }',
    '      vec4 cb = uProj * vec4(b, 1.0); vec2 huv = cb.xy / cb.w * 0.5 + 0.5;',
    '      vec2 edge = smoothstep(vec2(0.0), vec2(0.07), huv) * smoothstep(vec2(1.0), vec2(0.93), huv);',
    '      vec3 hw = (uInvView * vec4(b, 1.0)).xyz;',
    '      vec4 pc = uPrevViewProj * vec4(hw, 1.0); vec2 puv = pc.xy / pc.w * 0.5 + 0.5;',
    '      float conf = edge.x * edge.y * (1.0 - float(i) / float(steps));',
    '      if (any(lessThan(puv, vec2(0.0))) || any(greaterThan(puv, vec2(1.0)))) conf = 0.0;',
    '      return vec4(puv, conf, 1.0);',
    '    }',
    '  }',
    '  return vec4(0.0); }',
    'vec3 envReflection(vec3 R, float rough){',
    '  vec3 Rr = normalize(vec3(R.x, max(R.y, 0.01), R.z));',
    '  vec3 sky = skyRadiance(Rr);',
    '  sky = flatClouds(Rr, sky);',
    '  if (uFeatures.w > 0.5) { vec3 pr = textureLod(uProbe, R, rough * 6.0).rgb; sky = mix(sky, pr, R.y < 0.15 ? 1.0 : 0.7); }',
    '  else if (R.y < 0.0) sky = mix(sky, texelFetch(uAmbientTex, ivec2(1, 0), 0).rgb * 0.15, saturate(-R.y * 3.0));',
    '  return sky; }',
    '/* Directional sky irradiance (as average radiance, E/pi): cosine-weighted taps of the',
    '   sky-view LUT around the normal; below-horizon taps see the lit ground instead. */',
    'vec3 skyIrradianceDir(vec3 N, vec3 groundC){',
    '  vec3 T = normalize(abs(N.y) < 0.95 ? cross(N, vec3(0.0, 1.0, 0.0)) : cross(N, vec3(1.0, 0.0, 0.0))); vec3 B = cross(N, T);',
    '  vec3 acc = vec3(0.0); float wsum = 0.0;',
    '  for (int i = 0; i < 7; i++) {',
    '    vec3 dir; float w;',
    '    if (i == 0) { dir = N; w = 1.0; }',
    '    else { float a = float(i - 1) * 1.0472; dir = normalize(N * 0.5 + (T * cos(a) + B * sin(a)) * 0.866); w = 0.5; }',
    '    vec3 L = dir.y > 0.0 ? skyRadiance(normalize(vec3(dir.x, max(dir.y, 0.02), dir.z))) : groundC;',
    '    L = mix(groundC, L, smoothstep(-0.05, 0.08, dir.y));',
    '    acc += L * w; wsum += w;',
    '  }',
    '  return acc / wsum; }',
    'void main(){',
    '  float d = texture(uDepth, vUv).r;',
    '  vec3 vdir = viewRay(vUv);',
    '  if (isSkyDepth(d)) {',
    '    vec3 c = skyColorFull(vdir, vUv, true);',
    '    // weather fog swallows the horizon',
    '    float fh = uFog.w * saturate(1.0 - vdir.y * 2.0) ;',
    '    c = mix(c, fogInscatter(vdir), saturate(fh * 0.95 + (1.0 - saturate(vdir.y * 12.0)) * 0.1));',
    '    oColor = vec4(c, 1.0); return;',
    '  }',
    '  vec4 ga = texture(uGAlbedo, vUv), gn = texture(uGNormal, vUv), gm = texture(uGMaterial, vUv);',
    '  vec3 albedo = pow(ga.rgb, vec3(2.2));',
    '  vec3 N = normalize(gn.xyz); float rough = gn.w; float metal = gm.r; float film = gm.g; float trans = gm.b; float emis = gm.a;',
    '  // specular anti-aliasing: widen roughness where normals vary across the pixel (Kaplanyan 2016)',
    '  vec3 dNx = dFdx(N), dNy = dFdy(N);',
    '  float nvar = min(dot(dNx, dNx) + dot(dNy, dNy), 1.0);',
    '  rough = sqrt(min(rough * rough + min(nvar * 0.5, 0.18), 1.0));',
    '  vec3 vp = viewPosFromDepth(vUv, d);',
    '  vec3 wp = (uInvView * vec4(vp, 1.0)).xyz;',
    '  float dist = length(vp);',
    '  vec3 V = -vdir;',
    '  vec3 L = uSunDir.xyz;',
    '  // ---- shadows',
    '  float sh = sampleShadow(wp, N, dist, gl_FragCoord.xy);',
    '  if (uFeatures.z > 0.5 && dist < 60.0 && dot(N, L) > 0.0 && trans < 0.3) { vec3 Lv = normalize((uView * vec4(L, 0.0)).xyz); sh *= mix(contactShadow(vp, Lv, gl_FragCoord.xy), 1.0, saturate(dist / 60.0)); }',
    '  if (uPT.y > 0.5 && sh > 0.002 && dot(N, L) > 0.0 && dist < 400.0) sh = min(sh, mix(rtSunShadow(wp, N, vp, L, gl_FragCoord.xy, trans > 0.3), 1.0, smoothstep(250.0, 400.0, dist)));',
    '  // distant terrain: mountain shadows far beyond the cascades + valley sky occlusion',
    '  vec2 ffl = farTerrainLight(wp);',
    '  sh = min(sh, ffl.x);',
    '  vec2 cp = wp.xz + L.xz / max(L.y, 0.08) * max(uCloudParams.y - wp.y, 0.0);',
    '  float cloudSh = 1.0 - cloudCoverageAt(cp) * uMisc2.w;',
    '  vec3 lightC = uSunColor.rgb * sh * cloudSh;',
    '  // ---- direct light',
    '  float matAO = ga.a;',
    '  vec3 col = shadeDirectMS(N, V, L, albedo, rough, metal, 1.0 + film, matAO) * lightC;',
    '  if (trans > 0.0) {',
    '    float back = pow(saturate(dot(vdir, L)), 4.0) * 1.6 + saturate(-dot(N, L)) * 0.35;',
    '    col += albedo * uSunColor.rgb * cloudSh * trans * back * mix(0.25, 1.0, sh) * ffl.x;',
    '  }',
    '  // ---- ambient / indirect',
    '  vec4 aoT = uFeatures2.x > 0.5 ? texture(uAOTex, vUv) : vec4(0.0, 0.0, 0.0, 1.0);',
    '  float ao = min(ga.a, aoT.a);',
    '  vec3 skyUp = texelFetch(uAmbientTex, ivec2(0, 0), 0).rgb / PI, skyH = texelFetch(uAmbientTex, ivec2(1, 0), 0).rgb / PI;',
    '  float up = N.y * 0.5 + 0.5;',
    '  vec3 ground = uSkyAmb2.rgb * uSunColor.rgb * max(uTrueSunDir.y, 0.0) * cloudSh * 0.35 + skyH * 0.08;',
    '  vec3 skyIrr = mix(skyH * 0.8, skyUp, up * up);',
    '  vec3 irr = skyIrr * mix(0.35, 1.0, up) + ground * (1.0 - up);',
    '  // directional sky: warm sunset sides, blue shade from the open sky, calibrated to the ambient model',
    '  if (dist < 3000.0) { vec3 dirIrr = skyIrradianceDir(N, ground); float cal = (luma(skyUp) + 1e-4) / (luma(skyRadiance(vec3(0.0, 1.0, 0.0))) + 1e-4); irr = mix(irr, dirIrr * min(cal, 3.0), 0.65); }',
    '  if (uFeatures.y > 0.5) irr += aoT.rgb * uSkyAmb2.w;',
    '  irr *= uSkyAmb1.w * mix(1.0, ffl.y, 0.85);',
    '  // path-traced incoming radiance replaces the ambient model (occlusion + coloured multi-bounce)',
    '  vec4 ptS = vec4(0.0); float ptConf = 0.0;',
    '  if (uPT.x > 0.5) {',
    '    vec4 ptD = ptUpsample(uPTDiff, vUv, -vp.z);',
    '    ptConf = saturate(ptD.a / 3.0);',
    '    irr = mix(irr, ptD.rgb, ptConf);',
    '    ao = mix(ao, ga.a, ptConf);',
    '    ptS = ptUpsample(uPTSpec, vUv, -vp.z);',
    '  }',
    '  vec3 f0 = mix(vec3(0.04), albedo, metal); f0 = mix(f0, vec3(0.02), film);',
    '  float NoV = max(dot(N, V), 1e-3);',
    '  vec2 AB = envBRDFAB(rough, NoV);',
    '  vec3 spec = (f0 * AB.x + AB.y) * specEnergyComp(f0, AB);',
    '  col += albedo * (1.0 - metal) * irr * ao * (1.0 - (f0 * AB.x + AB.y));',
    '  // ---- reflections',
    '  vec3 R = reflect(vdir, N);',
    '  float specOcc = saturate(pow(NoV + ao, exp2(-16.0 * rough - 1.0)) - 1.0 + ao);',
    '  vec3 refl = envReflection(R, rough) * mix(1.0, cloudSh, 0.3) * mix(1.0, ffl.y, 0.6);',
    '  if (uFeatures.x > 0.5 && rough < 0.42 && dist < 800.0) {',
    '    vec3 rv = normalize((uView * vec4(R, 0.0)).xyz);',
    '    vec4 hit = traceSSR(vp, rv, uFeatures.x > 1.5 ? 48 : 24, ign(gl_FragCoord.xy));',
    '    if (hit.w > 0.0) { vec3 hc = texture(uPrevHDR, hit.xy).rgb; float w = hit.z * smoothstep(0.42, 0.15, rough); refl = mix(refl, hc, w); }',
    '  }',
    '  if (uPT.x > 0.5) refl = mix(refl, ptS.rgb, ptConf * smoothstep(0.9, 0.5, rough));',
    '  col += refl * spec * specOcc * mix(1.0, 1.6, film);',
    '  // ---- emissive',
    '  col += albedo * emis * 6.0;',
    '  // ---- point lights (campfires, lanterns)',
    '  for (int i = 0; i < 8; i++) {',
    '    if (i >= uNumLights) break;',
    '    vec3 lv = uLightPos[i].xyz - wp; float ld = length(lv); float r = uLightPos[i].w;',
    '    if (ld > r) continue;',
    '    vec3 Ld = lv / ld; float att = sq(saturate(1.0 - sq(ld / r))) / (1.0 + ld * ld * 0.5);',
    '    col += shadeDirect(N, V, Ld, albedo, rough, metal, 1.0) * uLightCol[i].rgb * att;',
    '  }',
    '  // ---- flashlight',
    '  if (uFlash.w > 0.0) {',
    '    vec3 lv = uCamPos.xyz + vec3(0.0, -0.25, 0.0) - wp; float ld = length(lv); vec3 Ld = lv / ld;',
    '    float cone = smoothstep(0.86, 0.97, dot(-Ld, uFlash.xyz));',
    '    col += shadeDirect(N, V, Ld, albedo, rough, metal, 1.0) * vec3(1.0, 0.93, 0.82) * uFlash.w * cone / (1.0 + ld * ld * 0.08);',
    '  }',
    '  // ---- underwater caustics (terrain below the local sea level)',
    '  if (uFeatures2.z > 0.5 && wp.y < uTexOrigin.w - 0.1) {',
    '    vec2 cq = wp.xz * 0.35 + uCamPos.w * 0.3;',
    '    float ca = pow(abs(sin(cq.x + sin(cq.y * 1.3 + uCamPos.w)) * sin(cq.y * 0.9 + sin(cq.x * 1.1 - uCamPos.w * 0.7))), 6.0);',
    '    col += albedo * lightC * ca * 1.5 * exp(-(uTexOrigin.w - wp.y) * 0.25);',
    '  }',
    '  // ---- aerial perspective / height fog',
    '  float T = fogTransmittance(uCamPos.xyz, wp);',
    '  col = col * T + fogInscatter(vdir) * (1.0 - T);',
    '  // volumetric clouds in front of geometry',
    '  if (uCloudMode == 1) { vec4 cl = texture(uCloudTex, vUv); col = col * cl.a + cl.rgb; }',
    '  oColor = vec4(col, 1.0);',
    '}'
  ].join('\n');

  /* ---------------- volumetric light shafts (half resolution) ---------------- */
  S.volumetricFS = [
    '#include <frame>',
    '#include <common>',
    '#include <shadows>',
    '#include <farfield>',
    '#include <atmosphere>',
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uDepth; uniform int uSteps; uniform float uMaxDist; uniform float uStrength;',
    'float shadowAt(vec3 p, float dist){',
    '  int ci = dist < uShadowSplits.x ? 0 : (dist < uShadowSplits.y ? 1 : (dist < uShadowSplits.z ? 2 : 3));',
    '  if (ci >= int(uShadowParams.y)) return 1.0;',
    '  vec4 sc = uShadowMat[ci] * vec4(p, 1.0); vec3 s = sc.xyz / sc.w;',
    '#ifndef REVERSED_Z',
    '  s.z = s.z * 0.5 + 0.5;',
    '#endif',
    '  s.xy = s.xy * 0.5 + 0.5;',
    '  if (any(lessThan(s.xy, vec2(0.0))) || any(greaterThan(s.xy, vec2(1.0)))) return 1.0;',
    '  return texture(uShadowMap, vec4(s.xy, float(ci), s.z - 0.001)); }',
    'void main(){',
    '  float d = texture(uDepth, vUv).r;',
    '  vec3 rd = viewRay(vUv);',
    '  float dist = isSkyDepth(d) ? uMaxDist : min(length(viewPosFromDepth(vUv, d)), uMaxDist);',
    '  float st = dist / float(uSteps);',
    '  float j = ign(gl_FragCoord.xy);',
    '  float mu = dot(rd, uSunDir.xyz);',
    '  float phase = henyeyGreenstein(mu, 0.55) * 0.8 + henyeyGreenstein(mu, -0.1) * 0.2;',
    '  float acc = 0.0, trans = 1.0;',
    '  float dens0 = uFog.x * 0.6 + 0.00035 + uFog.w * 0.004;',
    '  for (int i = 0; i < 48; i++) {',
    '    if (i >= uSteps) break;',
    '    float t = (float(i) + j) * st;',
    '    vec3 p = uCamPos.xyz + rd * t;',
    '    float hd = exp(-max(p.y - uFog.z, 0.0) * uFog.y);',
    '    float n = uFog.w > 0.05 ? vnoise3(p * 0.035 + vec3(uCamPos.w * 0.3 * uWind.x, 0.0, uCamPos.w * 0.3 * uWind.y)) : 0.5;',
    '    float dens = dens0 * hd * (0.5 + n);',
    '    float s = shadowAt(p, t) * farTerrainLight(p).x;',
    '    acc += s * dens * trans * st;',
    '    trans *= exp(-dens * st);',
    '  }',
    '  vec3 sunC = uSunColor.rgb;',
    '  o = vec4(sunC * acc * phase * uStrength * 4.0, trans);',
    '}'
  ].join('\n');

  /* ---------------- bloom ---------------- */
  S.bloomDownFS = [
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uSrc; uniform vec2 uTexel; uniform float uThreshold; uniform int uFirst;',
    'vec3 samp(vec2 uv){ return texture(uSrc, uv).rgb; }',
    'void main(){',
    '  vec2 t = uTexel;',
    '  vec3 a = samp(vUv + t * vec2(-2, -2)), b = samp(vUv + t * vec2(0, -2)), c = samp(vUv + t * vec2(2, -2));',
    '  vec3 d = samp(vUv + t * vec2(-2, 0)), e = samp(vUv), f = samp(vUv + t * vec2(2, 0));',
    '  vec3 g = samp(vUv + t * vec2(-2, 2)), h = samp(vUv + t * vec2(0, 2)), i = samp(vUv + t * vec2(2, 2));',
    '  vec3 j = samp(vUv + t * vec2(-1, -1)), k = samp(vUv + t * vec2(1, -1)), l = samp(vUv + t * vec2(-1, 1)), m = samp(vUv + t * vec2(1, 1));',
    '  vec3 c0 = e * 0.125 + (a + c + g + i) * 0.03125 + (b + d + f + h) * 0.0625 + (j + k + l + m) * 0.125;',
    '  if (uFirst == 1) { float br = max(c0.r, max(c0.g, c0.b)); float w = max(br - uThreshold, 0.0) / max(br, 1e-4); c0 *= w; c0 = min(c0, vec3(60.0)); }',
    '  o = vec4(c0, 1.0);',
    '}'
  ].join('\n');
  S.bloomUpFS = [
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uSrc; uniform vec2 uTexel; uniform float uRadius;',
    'void main(){',
    '  vec2 t = uTexel * uRadius;',
    '  vec3 c = texture(uSrc, vUv + vec2(-t.x, t.y)).rgb + texture(uSrc, vUv + vec2(0, t.y)).rgb * 2.0 + texture(uSrc, vUv + t).rgb;',
    '  c += texture(uSrc, vUv + vec2(-t.x, 0)).rgb * 2.0 + texture(uSrc, vUv).rgb * 4.0 + texture(uSrc, vUv + vec2(t.x, 0)).rgb * 2.0;',
    '  c += texture(uSrc, vUv - t).rgb + texture(uSrc, vUv + vec2(0, -t.y)).rgb * 2.0 + texture(uSrc, vUv + vec2(t.x, -t.y)).rgb;',
    '  o = vec4(c / 16.0, 1.0);',
    '}'
  ].join('\n');

  /* ---------------- auto exposure ---------------- */
  S.lumFS = [
    'in vec2 vUv; out vec4 o; uniform sampler2D uSrc;',
    'void main(){ vec3 c = texture(uSrc, vUv).rgb; float l = dot(c, vec3(0.2126, 0.7152, 0.0722));',
    '  // centre-weighted metering',
    '  float w = 1.0 - smoothstep(0.2, 0.75, length(vUv - 0.5)) * 0.7;',
    '  // expose for the land, like a photographer: the upper frame (mostly sky) counts less',
    '  w *= mix(1.0, 0.4, smoothstep(0.55, 0.92, vUv.y));',
    '  o = vec4(log2(max(l, 1e-5)) * w, w, 0.0, 1.0); }'
  ].join('\n');
  S.adaptFS = [
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uLum; uniform sampler2D uPrev; uniform float uDt; uniform float uBias; uniform float uLevel; uniform float uReset;',
    'void main(){',
    '  vec4 l = textureLod(uLum, vec2(0.5), uLevel);',
    '  float avgLog = l.r / max(l.g, 1e-4);',
    '  float avg = exp2(avgLog);',
    '  float target = 0.16 / clamp(avg, 0.0004, 40.0);',
    '  target = clamp(target, 0.03, 60.0) * exp2(uBias);',
    '  float prev = texture(uPrev, vec2(0.5)).r;',
    '  if (uReset > 0.5 || prev <= 0.0 || prev != prev) prev = target;',
    '  float speed = target < prev ? 2.2 : 1.1;',
    '  float e = mix(prev, target, 1.0 - exp(-uDt * speed));',
    '  o = vec4(e, avg, 0.0, 1.0);',
    '}'
  ].join('\n');

  /* ---------------- depth of field ---------------- */
  S.dofFS = [
    '#include <frame>',
    '#include <common>',
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uSrc; uniform sampler2D uDepth; uniform float uFocus; uniform float uAperture;',
    'float coc(vec2 uv){ float z = linearDepth(texture(uDepth, uv).r); return clamp(abs(z - uFocus) / max(z, 0.1) * uAperture, 0.0, 1.0); }',
    'void main(){',
    '  float c0 = coc(vUv);',
    '  vec3 acc = texture(uSrc, vUv).rgb; float wsum = 1.0;',
    '  float r = c0 * 12.0;',
    '  for (int i = 0; i < 24; i++) {',
    '    float a = float(i) * 2.39996; float rr = sqrt(float(i) / 24.0) * r;',
    '    vec2 uv = vUv + vec2(cos(a), sin(a)) * rr * uScreen.zw * 2.0;',
    '    float ci = coc(uv); float w = saturate(ci * 12.0 - rr + 1.0);',
    '    acc += texture(uSrc, uv).rgb * w; wsum += w;',
    '  }',
    '  o = vec4(acc / wsum, c0);',
    '}'
  ].join('\n');

  /* ---------------- composite: exposure, bloom, volumetrics, motion blur, grading ---------------- */
  S.compositeFS = [
    '#include <frame>',
    '#include <common>',
    '#include <tonemap>',
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uHDR; uniform sampler2D uBloom; uniform sampler2D uExposure; uniform sampler2D uVolTex; uniform sampler2D uDepth; uniform sampler2D uDof;',
    'uniform vec4 uGrade;    // x contrast, y saturation, z temperature, w vignette',
    'uniform vec4 uGrade2;   // x grain, y bloom strength, z motion blur, w dof',
    'uniform vec4 uGrade3;   // x volumetric on, y underwater, z damage/flash, w exposure multiplier',
    'uniform vec3 uWaterTint; uniform int uTonemap;',
    'vec3 sampleHDR(vec2 uv){ return texture(uHDR, uv).rgb; }',
    'void main(){',
    '  vec2 uv = vUv;',
    '  if (uGrade3.y > 0.5) uv += vec2(sin(uv.y * 40.0 + uCamPos.w * 2.0), cos(uv.x * 30.0 + uCamPos.w * 1.7)) * 0.0025;',
    '  vec3 c = sampleHDR(uv);',
    '  if (uGrade2.w > 0.5) { vec4 dd = texture(uDof, uv); c = mix(c, dd.rgb, saturate(dd.a * 3.0)); }',
    '  // camera motion blur via depth reprojection',
    '  if (uGrade2.z > 0.0) {',
    '    float d = texture(uDepth, uv).r;',
    '    vec3 wp = isSkyDepth(d) ? uCamPos.xyz + viewRay(uv) * 5000.0 : (uInvView * vec4(viewPosFromDepth(uv, d), 1.0)).xyz;',
    '    vec4 pc = uPrevViewProj * vec4(wp, 1.0); vec2 puv = pc.xy / pc.w * 0.5 + 0.5;',
    '    vec2 vel = (uv - puv) * uGrade2.z; float vl = length(vel);',
    '    if (vl > 0.0008) { vel *= min(1.0, 0.04 / vl); vec3 acc = c; for (int i = 1; i < 8; i++) acc += sampleHDR(uv - vel * float(i) / 8.0); c = acc / 8.0; }',
    '  }',
    '  if (uGrade3.x > 0.5) { vec4 v = texture(uVolTex, uv); c = c * mix(1.0, v.a, 0.35) + v.rgb; }',
    '  c += texture(uBloom, uv).rgb * uGrade2.y;',
    '  if (uGrade3.y > 0.5) {',
    '    float d = texture(uDepth, uv).r; float z = isSkyDepth(d) ? 200.0 : linearDepth(d);',
    '    float f = 1.0 - exp(-z * 0.09);',
    '    c = mix(c * uWaterTint * 2.0, uWaterTint * 0.3 * luma(uSunColor.rgb + 0.02), f);',
    '  }',
    '  float exposure = texture(uExposure, vec2(0.5)).r * uGrade3.w;',
    '  c *= exposure;',
    '  // white balance (temperature)',
    '  c *= vec3(1.0 + uGrade.z * 0.1, 1.0, 1.0 - uGrade.z * 0.1);',
    '  c = uTonemap == 1 ? AgX(c * 1.25) : ACESFitted(c * 1.1);',
    '  // grading in display space',
    '  c = pow(c, vec3(1.0 / 2.2));',
    '  float l = luma(c);',
    '  c = mix(vec3(l), c, uGrade.y);',
    '  c = (c - 0.5) * uGrade.x + 0.5;',
    '  // subtle filmic toe: lift shadows slightly toward blue, highlights warm',
    '  c += vec3(-0.004, 0.0, 0.01) * (1.0 - l) + vec3(0.01, 0.004, -0.008) * l;',
    '  float vig = 1.0 - uGrade.w * pow(length((vUv - 0.5) * vec2(1.0, 0.8)) * 1.35, 2.5);',
    '  c *= vig;',
    '  c += (hash12(gl_FragCoord.xy + fract(uCamPos.w) * 91.7) - 0.5) * uGrade2.x;',
    '  c += (hash12(gl_FragCoord.xy * 1.3 + 17.0) - 0.5) / 255.0;',
    '  c = mix(c, vec3(1.0), uGrade3.z);',
    '  o = vec4(saturate(c), luma(saturate(c)));',
    '}'
  ].join('\n');

  /* ---------------- FXAA 3.11 (quality preset ~12) ---------------- */

  /* Temporal anti-aliasing. Resolves the sub-pixel jittered frame against a reprojected
   * history (camera motion from depth), Catmull-Rom history fetch, variance clipping in
   * tonemapped YCoCg and motion-adaptive blending. Converges dithered LOD fades, alpha-
   * tested leaves, grass blades and specular shimmer. Water (no depth) is tagged via
   * HDR alpha < 0.75 and gets a short history. */
  S.taaFS = [
    '#include <frame>',
    '#include <common>',
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uCur; uniform sampler2D uHist; uniform sampler2D uDepth; uniform sampler2D uExposure;',
    'uniform mat4 uCurVP; uniform mat4 uPrevVP; uniform float uReset; uniform vec2 uTexel;',
    'vec3 toY(vec3 c){ return vec3(0.25 * c.r + 0.5 * c.g + 0.25 * c.b, 0.5 * c.r - 0.5 * c.b, -0.25 * c.r + 0.5 * c.g - 0.25 * c.b); }',
    'vec3 fromY(vec3 c){ return vec3(c.x + c.y - c.z, c.x + c.z, c.x - c.y - c.z); }',
    'vec3 tm(vec3 c, float e){ c *= e; return c / (1.0 + max(c.r, max(c.g, c.b))); }',
    'vec3 itm(vec3 c, float e){ return c / max(1.0 - max(c.r, max(c.g, c.b)), 1e-3) / e; }',
    'vec3 histCR(vec2 uv){',
    '  vec2 size = 1.0 / uTexel; vec2 sp = uv * size; vec2 tp = floor(sp - 0.5) + 0.5; vec2 f = sp - tp;',
    '  vec2 w0 = f * (-0.5 + f * (1.0 - 0.5 * f)), w1 = 1.0 + f * f * (-2.5 + 1.5 * f);',
    '  vec2 w2 = f * (0.5 + f * (2.0 - 1.5 * f)), w3 = f * f * (-0.5 + 0.5 * f);',
    '  vec2 w12 = w1 + w2, t12 = (tp + w2 / w12) * uTexel, t0 = (tp - 1.0) * uTexel, t3 = (tp + 2.0) * uTexel;',
    '  vec3 r = texture(uHist, vec2(t12.x, t0.y)).rgb * (w12.x * w0.y) + texture(uHist, vec2(t0.x, t12.y)).rgb * (w0.x * w12.y)',
    '         + texture(uHist, t12).rgb * (w12.x * w12.y) + texture(uHist, vec2(t3.x, t12.y)).rgb * (w3.x * w12.y)',
    '         + texture(uHist, vec2(t12.x, t3.y)).rgb * (w12.x * w3.y);',
    '  float ws = w12.x * w0.y + w0.x * w12.y + w12.x * w12.y + w3.x * w12.y + w12.x * w3.y;',
    '  return max(r / ws, vec3(0.0));',
    '}',
    'void main(){',
    '  ivec2 px = ivec2(gl_FragCoord.xy), mxp = ivec2(1.0 / uTexel) - 1;',
    '  vec4 c0 = texelFetch(uCur, px, 0);',
    '  float e = texture(uExposure, vec2(0.5)).r; e = e > 0.0 && e < 1e4 ? e : 1.0;',
    '  if (uReset > 0.5) { o = c0; return; }',
    '  bool water = c0.a < 0.75;',
    '  // 3x3 neighbourhood statistics; nearest depth for silhouette-dilated reprojection',
    '  vec3 cur = toY(tm(c0.rgb, e)), m1 = vec3(0.0), m2 = vec3(0.0), mn = cur, mx = cur;',
    '  float dBest = texelFetch(uDepth, px, 0).r; ivec2 pBest = px;',
    '  for (int j = -1; j <= 1; j++) for (int i = -1; i <= 1; i++) {',
    '    ivec2 q = clamp(px + ivec2(i, j), ivec2(0), mxp);',
    '    vec3 s = toY(tm(texelFetch(uCur, q, 0).rgb, e));',
    '    m1 += s; m2 += s * s; mn = min(mn, s); mx = max(mx, s);',
    '    float dq = texelFetch(uDepth, q, 0).r;',
    '#ifdef REVERSED_Z',
    '    if (dq > dBest) { dBest = dq; pBest = q; }',
    '#else',
    '    if (dq < dBest) { dBest = dq; pBest = q; }',
    '#endif',
    '  }',
    '  m1 /= 9.0; vec3 sig = sqrt(max(m2 / 9.0 - m1 * m1, vec3(0.0)));',
    '  // reproject (homogeneous, so sky points at infinity work too)',
    '  vec2 uvB = (vec2(pBest) + 0.5) * uTexel;',
    '  vec4 h = uInvViewProj * vec4(uvB * 2.0 - 1.0, depthToNDC(dBest), 1.0);',
    '  vec4 cc = uCurVP * h, pc = uPrevVP * h;',
    '  vec2 vel = (cc.xy / cc.w - pc.xy / pc.w) * 0.5;',
    '  vec2 uvH = vUv - vel;',
    '  if (any(lessThan(uvH, vec2(0.0))) || any(greaterThan(uvH, vec2(1.0))) || pc.w <= 0.0 && h.w != 0.0) { o = c0; return; }',
    '  float speed = length(vel / uTexel);',
    '  vec3 hist = toY(tm(histCR(uvH), e));',
    '  float g = mix(1.25, 0.8, saturate(speed / 6.0)) * (water ? 0.8 : 1.0);',
    '  vec3 lo = max(mn, m1 - g * sig), hi = min(mx, m1 + g * sig);',
    '  // clip toward the neighbourhood mean (less flicker than a hard clamp)',
    '  vec3 cen = 0.5 * (lo + hi), ext = max(0.5 * (hi - lo), vec3(1e-4)), dv = hist - cen;',
    '  vec3 ad = abs(dv / ext); float mo = max(ad.x, max(ad.y, ad.z));',
    '  if (mo > 1.0) hist = cen + dv / mo;',
    '  float a = mix(0.075, 0.22, saturate(speed / 12.0));',
    '  if (water) a = max(a, 0.3);',
    '  // luminance-weighted blend (suppresses fireflies)',
    '  float wc = a / (1.0 + cur.x), wh = (1.0 - a) / (1.0 + hist.x);',
    '  vec3 res = (cur * wc + hist * wh) / (wc + wh);',
    '  o = vec4(max(itm(fromY(res), e), vec3(0.0)), c0.a);',
    '}'
  ].join('\n');

  S.fxaaFS = [
    'in vec2 vUv; out vec4 o;',
    'uniform sampler2D uSrc; uniform vec2 uTexel; uniform int uEnabled;',
    'float L(vec2 uv){ return texture(uSrc, uv).a; }',
    'void main(){',
    '  vec4 cM = texture(uSrc, vUv);',
    '  if (uEnabled == 0) { o = vec4(cM.rgb, 1.0); return; }',
    '  if (uEnabled == 2) {',
    '    // after TAA: light contrast-adaptive sharpening instead of FXAA',
    '    vec3 n = texture(uSrc, vUv + vec2(0, uTexel.y)).rgb, s2 = texture(uSrc, vUv - vec2(0, uTexel.y)).rgb;',
    '    vec3 e2 = texture(uSrc, vUv + vec2(uTexel.x, 0)).rgb, w = texture(uSrc, vUv - vec2(uTexel.x, 0)).rgb;',
    '    vec3 mnC = min(cM.rgb, min(min(n, s2), min(e2, w))), mxC = max(cM.rgb, max(max(n, s2), max(e2, w)));',
    '    vec3 amp = sqrt(clamp(min(mnC, 1.0 - mxC) / max(mxC, 1e-4), 0.0, 1.0));',
    '    vec3 wgt = -amp * 0.16;',
    '    vec3 r = (cM.rgb + (n + s2 + e2 + w) * wgt) / (1.0 + 4.0 * wgt);',
    '    o = vec4(clamp(r, 0.0, 1.0), 1.0); return;',
    '  }',
    '  float lM = cM.a, lN = L(vUv + vec2(0, uTexel.y)), lS = L(vUv - vec2(0, uTexel.y)), lE = L(vUv + vec2(uTexel.x, 0)), lW = L(vUv - vec2(uTexel.x, 0));',
    '  float mx = max(max(max(lN, lS), max(lE, lW)), lM), mn = min(min(min(lN, lS), min(lE, lW)), lM);',
    '  float range = mx - mn;',
    '  if (range < max(0.0312, mx * 0.125)) { o = vec4(cM.rgb, 1.0); return; }',
    '  float lNW = L(vUv + vec2(-uTexel.x, uTexel.y)), lNE = L(vUv + uTexel), lSW = L(vUv - uTexel), lSE = L(vUv + vec2(uTexel.x, -uTexel.y));',
    '  float edgeH = abs(-2.0 * lW + lNW + lSW) + abs(-2.0 * lM + lN + lS) * 2.0 + abs(-2.0 * lE + lNE + lSE);',
    '  float edgeV = abs(-2.0 * lS + lSW + lSE) + abs(-2.0 * lM + lW + lE) * 2.0 + abs(-2.0 * lN + lNW + lNE);',
    '  bool horz = edgeH >= edgeV;',
    '  float l1 = horz ? lS : lW, l2 = horz ? lN : lE;',
    '  float g1 = abs(l1 - lM), g2 = abs(l2 - lM);',
    '  float stepL = horz ? uTexel.y : uTexel.x;',
    '  float lLocal; float grad;',
    '  if (g1 >= g2) { stepL = -stepL; lLocal = 0.5 * (l1 + lM); grad = g1; } else { lLocal = 0.5 * (l2 + lM); grad = g2; }',
    '  vec2 cur = vUv; if (horz) cur.y += stepL * 0.5; else cur.x += stepL * 0.5;',
    '  vec2 off = horz ? vec2(uTexel.x, 0.0) : vec2(0.0, uTexel.y);',
    '  vec2 p1 = cur - off, p2 = cur + off; float e1 = L(p1) - lLocal, e2 = L(p2) - lLocal;',
    '  bool d1 = abs(e1) >= grad * 0.25, d2 = abs(e2) >= grad * 0.25;',
    '  const float Q[8] = float[](1.0, 1.5, 2.0, 2.0, 2.0, 2.0, 4.0, 8.0);',
    '  for (int i = 0; i < 8; i++) {',
    '    if (d1 && d2) break;',
    '    if (!d1) { p1 -= off * Q[i]; e1 = L(p1) - lLocal; d1 = abs(e1) >= grad * 0.25; }',
    '    if (!d2) { p2 += off * Q[i]; e2 = L(p2) - lLocal; d2 = abs(e2) >= grad * 0.25; }',
    '  }',
    '  float dist1 = horz ? vUv.x - p1.x : vUv.y - p1.y, dist2 = horz ? p2.x - vUv.x : p2.y - vUv.y;',
    '  bool isDir1 = dist1 < dist2; float dmin = min(dist1, dist2); float edgeLen = dist1 + dist2;',
    '  float pixOff = -dmin / edgeLen + 0.5;',
    '  bool lCenterSmaller = lM < lLocal;',
    '  bool correct = ((isDir1 ? e1 : e2) < 0.0) != lCenterSmaller;',
    '  float fo = correct ? pixOff : 0.0;',
    '  float lAvg = (1.0 / 12.0) * (2.0 * (lN + lS + lE + lW) + lNW + lNE + lSW + lSE);',
    '  float sub = clamp(abs(lAvg - lM) / range, 0.0, 1.0); float subF = (-2.0 * sub + 3.0) * sub * sub; float subOff = subF * subF * 0.75;',
    '  fo = max(fo, subOff);',
    '  vec2 fuv = vUv; if (horz) fuv.y += fo * stepL; else fuv.x += fo * stepL;',
    '  o = vec4(texture(uSrc, fuv).rgb, 1.0);',
    '}'
  ].join('\n');

  S.copyFS = ['in vec2 vUv; out vec4 o; uniform sampler2D uSrc; void main(){ o = texture(uSrc, vUv); }'].join('\n');
})();

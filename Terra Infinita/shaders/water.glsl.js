/* =============================================================================
 * TERRA INFINITA — water surface shader (oceans, lakes, rivers, waterfalls, lava)
 * Forward-rendered after deferred lighting. Uses the lit scene for refraction and
 * screen-space reflections, the sky model + reflection probe as fallback.
 * ========================================================================== */
(function () {
  'use strict';
  var S = TERRA.shaders;

  /* Shared wave spectrum: geometric wavelengths from 64 m down, directions spread around the
   * wind (short waves spread more), amplitudes steepness-limited. Lakes are fetch-limited
   * (shorter, choppier waves). Mirrored on the CPU in js/world/water.js for buoyancy. */
  S.lib.waves = [
    'void waveParam(int i, bool lake, out vec2 dir, out float wl, out float amp){',
    '  float fi = float(i);',
    '  wl = 64.0 * pow(0.7, fi) * (lake ? 0.3 : 1.0);',
    '  float spread = (hash11(fi * 7.13 + 1.0) - 0.5) * (0.9 + fi * 0.09);',
    '  float a0 = atan(uWind.y, uWind.x) + spread;',
    '  dir = vec2(cos(a0), sin(a0));',
    '  amp = wl * 0.0105 * (0.45 + 0.55 * hash11(fi * 3.1 + 2.0)) * (lake ? 0.6 : 1.0); }',
    '/* Gerstner displacement + analytic normal & Jacobian accumulation. */',
    'vec3 gerstnerW(vec2 p, vec2 dir, float amp, float wl, float t, float q, inout vec3 n, inout float jac, inout float crest){',
    '  float k = TAU / wl; float c = sqrt(9.8 / k); float f = k * (dot(dir, p) - c * t);',
    '  float sf = sin(f), cf = cos(f);',
    '  n.x -= dir.x * k * amp * cf; n.z -= dir.y * k * amp * cf; n.y -= q * k * amp * sf;',
    '  jac -= q * k * amp * sf; crest += amp * sf;',
    '  return vec3(dir.x * q * amp * cf, amp * sf, dir.y * q * amp * cf); }'
  ].join('\n');

  S.waterVS = [
    '#include <frame>',
    '#include <common>',
    '#include <waves>',
    'layout(location = 0) in vec3 aPos;',
    'layout(location = 1) in float aMorph;',
    'layout(location = 2) in vec2 aFlow;',
    'layout(location = 3) in vec4 aInfo;',
    'uniform vec3 uNodeOffset; uniform vec2 uMorphRange; uniform vec4 uNodeInfo; uniform float uWaveAmp;',
    'uniform sampler2D uSimTex; uniform vec4 uSimArea;',
    'out vec3 vWorld; out vec2 vFlow; flat out int vType; out vec3 vNormal; out float vSteep; out float vBase;',
    'void main(){',
    '  vec3 p = aPos + uNodeOffset;',
    '  float d = distance(p, uCamPos.xyz);',
    '  float m = saturate((d - uMorphRange.x) / (uMorphRange.y - uMorphRange.x));',
    '  p.y = mix(aPos.y, aMorph, m);',
    '  vBase = p.y;',
    '  vType = int(aInfo.x + 0.5);',
    '  vFlow = aFlow / 8000.0;',
    '  vec3 n = vec3(0.0, 1.0, 0.0);',
    '  if (vType == 1 || vType == 2) {',
    '    bool lake = vType == 2;',
    '    float A = uWaveAmp * (lake ? 0.06 + 0.5 * smoothstep(0.08, 0.6, uWind.z) : 1.0) * (1.0 - smoothstep(300.0, 1400.0, d));',
    '    float t = uCamPos.w; float jac = 1.0, crest = 0.0; vec3 disp = vec3(0.0);',
    '    for (int i = 0; i < 6; i++) {',
    '      vec2 dir; float wl, amp; waveParam(i, lake, dir, wl, amp);',
    '      disp += gerstnerW(p.xz, dir, amp * A, wl, t, 0.55, n, jac, crest);',
    '    }',
    '    p += disp;',
    '  }',
    '  // interactive ripples (player, rain) from the wave-equation simulation',
    '  vec2 suv = (p.xz - uSimArea.xy) / uSimArea.z;',
    '  if (uSimArea.w > 0.5 && all(greaterThan(suv, vec2(0.0))) && all(lessThan(suv, vec2(1.0)))) p.y += texture(uSimTex, suv).r * 0.5;',
    '  vNormal = normalize(n);',
    '  vSteep = 0.0;',
    '  vWorld = p;',
    '  gl_Position = uViewProj * vec4(p, 1.0);',
    '}'
  ].join('\n');

  S.waterFS = [
    '#include <frame>',
    '#include <common>',
    '#include <pbr>',
    '#include <shadows>',
    '#include <farfield>',
    '#include <atmosphere>',
    '#include <cloudCommon>',
    '#include <skyColor>',
    '#include <waves>',
    'in vec3 vWorld; in vec2 vFlow; flat in int vType; in vec3 vNormal; in float vSteep; in float vBase;',
    'out vec4 oColor;',
    'uniform sampler2D uSceneTex; uniform sampler2D uDepth; uniform sampler2D uNoiseTex;',
    'uniform samplerCube uProbe; uniform vec4 uWaterQ;   // x quality, y ssr, z probe, w -',
    'uniform sampler2D uTrailTex; uniform sampler2D uSimTex; uniform vec4 uSimArea; uniform float uWaveAmp;',
    'float gJac = 1.0, gCrest = 0.0, gSimV = 0.0;',
    'vec2 noiseGrad(vec2 p){',
    '  float e = 1.0 / 256.0;',
    '  float h = texture(uNoiseTex, p).g, hx = texture(uNoiseTex, p + vec2(e, 0.0)).g, hy = texture(uNoiseTex, p + vec2(0.0, e)).g;',
    '  return vec2(hx - h, hy - h) * 256.0; }',
    'vec3 waterNormal(vec3 wp, vec3 nGeo, float dist, int type){',
    '  float t = uCamPos.w;',
    '  vec2 g = vec2(0.0);',
    '  vec3 N;',
    '  if (type == 3) {',
    '    // flow-mapped river normals (two phases cross-faded)',
    '    vec2 f = vFlow; float sp = length(f);',
    '    float ph0 = fract(t * 0.35), ph1 = fract(t * 0.35 + 0.5);',
    '    float w0 = 1.0 - abs(ph0 * 2.0 - 1.0);',
    '    vec2 uv = wp.xz / 16.0;',
    '    vec2 g0 = noiseGrad(uv - f * ph0 * 0.18) + noiseGrad(uv * 2.7 - f * ph0 * 0.5) * 0.5;',
    '    vec2 g1 = noiseGrad(uv + 0.37 - f * ph1 * 0.18) + noiseGrad(uv * 2.7 + 0.21 - f * ph1 * 0.5) * 0.5;',
    '    g = mix(g1, g0, w0) * (0.05 + 0.05 * sp);',
    '    N = nGeo;',
    '  } else {',
    '    // full wave spectrum per pixel: exact Gerstner normals, short waves fade with distance',
    '    bool lake = type == 2;',
    '    // lakes go glassy in calm air (mirror reflections), ruffle as the wind picks up',
    '    float A = uWaveAmp * (lake ? 0.06 + 0.5 * smoothstep(0.08, 0.6, uWind.z) : 1.0);',
    '    vec3 n = vec3(0.0, 1.0, 0.0); float jac = 1.0, crest = 0.0;',
    '    vec2 pb = vec2(wp.x, wp.z);',
    '    for (int i = 0; i < 16; i++) {',
    '      vec2 dir; float wl, amp; waveParam(i, lake, dir, wl, amp);',
    '      float fade = 1.0 - smoothstep(wl * 30.0, wl * 90.0, dist);',
    '      if (fade <= 0.0) continue;',
    '      gerstnerW(pb, dir, amp * A * fade, wl, t, 0.5, n, jac, crest);',
    '    }',
    '    gJac = jac; gCrest = crest / max(A * 1.2, 0.05);',
    '    N = normalize(n);',
    '    // capillary detail',
    '    vec2 w = uWind.xy * t;',
    '    float cap = lake ? 0.08 + 1.2 * smoothstep(0.05, 0.5, uWind.z) : 1.0;',
    '    g += noiseGrad(wp.xz / 4.0 + w * 0.02 + vec2(t * 0.02, -t * 0.013)) * 0.018 * saturate(1.0 - dist / 120.0) * (0.4 + uWind.z) * cap;',
    '    g += noiseGrad(wp.xz / 1.3 - w.yx * 0.03) * 0.01 * saturate(1.0 - dist / 40.0) * (0.3 + uWind.z) * cap;',
    '  }',
    '  // interactive ripples from the wave-equation simulation',
    '  vec2 suv = (wp.xz - uSimArea.xy) / uSimArea.z;',
    '  bool inSim = uSimArea.w > 0.5 && all(greaterThan(suv, vec2(0.004))) && all(lessThan(suv, vec2(0.996)));',
    '  if (inSim) {',
    '    float e = 1.0 / 256.0;',
    '    vec2 hc = texture(uSimTex, suv).rg;',
    '    float hx = texture(uSimTex, suv + vec2(e, 0.0)).r - texture(uSimTex, suv - vec2(e, 0.0)).r;',
    '    float hz = texture(uSimTex, suv + vec2(0.0, e)).r - texture(uSimTex, suv - vec2(0.0, e)).r;',
    '    float edge = smoothstep(0.0, 0.08, min(min(suv.x, 1.0 - suv.x), min(suv.y, 1.0 - suv.y)));',
    '    g += vec2(hx, hz) / (2.0 * uSimArea.z * e) * 0.9 * edge;',
    '    gSimV = abs(hc.r - hc.g) * edge;',
    '  }',
    '  // distant rain ripples (the simulation covers the near field)',
    '  if (uWeather.w > 0.02 && dist < 150.0 && !inSim) {',
    '    vec2 p = wp.xz * 2.2; vec2 id = floor(p); vec2 fr = fract(p) - 0.5;',
    '    float r = hash12(id); float tt = fract(t * 1.1 + r); vec2 c = (hash22(id) - 0.5) * 0.5;',
    '    float dd = length(fr - c); float ring = sin((dd - tt * 0.45) * 50.0) * (1.0 - tt) * smoothstep(tt * 0.45 + 0.07, tt * 0.45, dd);',
    '    g += normalize(fr - c + 1e-4) * ring * uWeather.w * 0.35;',
    '  }',
    '  g *= 1.0 / (1.0 + dist * 0.004);',
    '  return normalize(N + vec3(-g.x, 0.0, -g.y));',
    '}',
    'void main(){',
    '  vec2 suv = gl_FragCoord.xy * uScreen.zw;',
    '  float sceneD = texture(uDepth, suv).r;',
    '  float sceneZ = isSkyDepth(sceneD) ? 1e7 : linearDepth(sceneD);',
    '  vec3 toP = vWorld - uCamPos.xyz; float dist = length(toP); vec3 vdir = toP / dist;',
    '  vec4 vpos = uView * vec4(vWorld, 1.0); float wz = -vpos.z;',
    '  if (wz > sceneZ + 0.05) discard;',
    '  vec3 V = -vdir;',
    '  // geometric normal from screen derivatives (captures rapids & waterfall slopes)',
    '  vec3 fn = normalize(cross(dFdx(vWorld), dFdy(vWorld))); if (fn.y < 0.0) fn = -fn;',
    '  float steep = saturate((1.0 - fn.y) * 3.0);',
    '  vec3 nGeo = vType == 3 ? normalize(mix(vNormal, fn, 0.8)) : vNormal;',
    '  bool under = uTrail.w > 0.5;',
    '  if (vType == 4) {',
    '    // ---- lava',
    '    float t = uCamPos.w;',
    '    vec2 uv = vWorld.xz / 30.0;',
    '    float n1 = texture(uNoiseTex, uv + vec2(t * 0.004, t * 0.003)).r, n2 = texture(uNoiseTex, uv * 3.0 - t * 0.01).g;',
    '    float crust = smoothstep(0.45, 0.62, n1 * 0.7 + n2 * 0.4);',
    '    vec3 hot = mix(vec3(9.0, 2.2, 0.3), vec3(14.0, 6.0, 1.0), n2);',
    '    vec3 cool = vec3(0.04, 0.03, 0.03) + hot * 0.02;',
    '    vec3 c = mix(hot, cool, crust) * (0.8 + 0.4 * sin(t * 1.5 + n1 * 10.0));',
    '    float T = fogTransmittance(uCamPos.xyz, vWorld);',
    '    oColor = vec4(c * T + fogInscatter(vdir) * (1.0 - T), 0.5); return;   // a < 0.75 tags water/lava for TAA',
    '  }',
    '  vec3 N = waterNormal(vWorld, nGeo, dist, vType);',
    '  if (under) N = -N;',
    '  float NoV = max(dot(N, V), 0.001);',
    '  // ---- refraction',
    '  float thick = max(sceneZ - wz, 0.0);',
    '  vec2 roff = N.xz * 0.06 * saturate(thick * 0.3) / max(1.0, dist * 0.05);',
    '  vec2 ruv = suv + roff;',
    '  float rd = texture(uDepth, ruv).r; float rz = isSkyDepth(rd) ? 1e7 : linearDepth(rd);',
    '  if (rz < wz) { ruv = suv; rz = sceneZ; }',
    '  float thickR = max(rz - wz, 0.0);',
    '  if (isSkyDepth(rd) && !under) thickR = 80.0;',
    '  // slight chromatic dispersion in the refraction',
    '  vec3 refr = vec3(texture(uSceneTex, ruv).r, texture(uSceneTex, suv + roff * 1.07).g, texture(uSceneTex, suv + roff * 1.15).b);',
    '  if (rz < wz) refr = texture(uSceneTex, ruv).rgb;',
    '  // absorption & in-scattering (depth-based colour)',
    '  vec3 absorb = vType == 3 ? vec3(0.45, 0.14, 0.09) : (vType == 2 ? vec3(0.38, 0.1, 0.075) : vec3(0.42, 0.075, 0.05));',
    '  float murk = vType == 3 ? 1.6 : 1.0;',
    '  float vpath = thickR * (under ? 0.2 : 1.0);',
    '  vec3 Tw = exp(-absorb * vpath * murk * 0.22);',
    '  vec3 sunC = uSunColor.rgb * farTerrainLight(vWorld).x;   // mountain shadows fall on lakes too',
    '  vec3 skyA = texelFetch(uAmbientTex, ivec2(0, 0), 0).rgb / PI;',
    '  vec3 deepC = (vType == 1 ? vec3(0.004, 0.028, 0.045) : (vType == 2 ? vec3(0.006, 0.03, 0.03) : vec3(0.012, 0.035, 0.03))) * (skyA * 3.0 + sunC * max(uSunDir.y, 0.0) * 0.25);',
    '  vec3 body = refr * Tw + deepC * (1.0 - Tw);',
    '  // ---- reflection',
    '  vec3 R = reflect(vdir, N);',
    '  vec3 refl;',
    '  if (under) { refl = deepC * 0.5; }',
    '  else {',
    '    vec3 Rr = normalize(vec3(R.x, max(R.y, 0.005), R.z));',
    '    refl = skyRadiance(Rr);',
    '    refl = flatClouds(Rr, refl);',
    '    if (uWaterQ.z > 0.5) refl = mix(refl, textureLod(uProbe, Rr, 0.0).rgb, 0.75);',
    '    if (uWaterQ.y > 0.5 && dist < 1500.0) {',
    '      vec3 rv = normalize((uView * vec4(R, 0.0)).xyz); vec3 vp = vpos.xyz;',
    '      float stepLen = 0.4 + wz * 0.012; vec3 p = vp + rv * stepLen * ign(gl_FragCoord.xy);',
    '      int steps = uWaterQ.x > 2.5 ? 48 : 28;',
    '      for (int i = 0; i < 48; i++) {',
    '        if (i >= steps) break;',
    '        p += rv * stepLen; stepLen *= 1.12;',
    '        vec4 c = uProj * vec4(p, 1.0); if (c.w <= 0.0) break; vec2 uv = c.xy / c.w * 0.5 + 0.5;',
    '        if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0)))) break;',
    '        float sdd = texture(uDepth, uv).r; if (isSkyDepth(sdd)) continue;',
    '        float sz = linearDepth(sdd);',
    '        if (-p.z > sz && -p.z - sz < max(1.0, stepLen * 3.0)) {',
    '          vec2 e = smoothstep(vec2(0.0), vec2(0.1), uv) * smoothstep(vec2(1.0), vec2(0.9), uv);',
    '          refl = mix(refl, texture(uSceneTex, uv).rgb, e.x * e.y); break; }',
    '      }',
    '    }',
    '  }',
    '  float F = 0.02 + 0.98 * pow(1.0 - NoV, 5.0);',
    '  if (under) F = NoV < 0.66 ? 1.0 : 0.05;',
    '  // subsurface scattering: sunlight transmitted through thin wave crests (seen against the sun)',
    '  vec3 Lh = normalize(vec3(uSunDir.x, 0.0, uSunDir.z) + 1e-4);',
    '  float sssV = pow(saturate(dot(vdir, Lh) * 0.5 + 0.5), 5.0) * saturate(gCrest * 0.6 + 0.4) * saturate(uSunDir.y * 3.0 + 0.2);',
    '  float sssN = saturate(dot(N, -Lh) * 0.5 + 0.35) * 0.35;',
    '  vec3 sssC = (vType == 1 ? vec3(0.03, 0.34, 0.30) : vec3(0.05, 0.28, 0.22)) * sunC * (sssV * 1.4 + sssN * 0.25) * (1.0 - F);',
    '  body += sssC * (under ? 0.0 : 1.0);',
    '  vec3 col = mix(body, refl, F);',
    '  // ---- sun glints',
    '  float sh = sampleShadow(vWorld, vec3(0.0, 1.0, 0.0), dist, gl_FragCoord.xy);',
    '  vec3 H = normalize(V + uSunDir.xyz);',
    '  float spec = D_GGX(saturate(dot(N, H)), 0.06) * 0.25;',
    '  col += sunC * spec * sh * F * 4.0;',
    '  // ---- foam: shorelines, rocks, rapids & waterfalls',
    '  float foamN = texture(uNoiseTex, vWorld.xz / 7.0 + vFlow * uCamPos.w * 0.05).a * 0.6 + texture(uNoiseTex, vWorld.xz / 2.3 - uCamPos.w * 0.02).b * 0.4;',
    '  // foam hugs the waterline and grows with wave energy (calm lakes barely foam)',
    '  float energy = saturate(0.25 + uWind.z * 1.3) * (vType == 1 ? 1.0 : 0.45);',
    '  float shore = smoothstep(0.5, 0.0, thick) * energy;',
    '  float wave = vType == 1 ? smoothstep(0.45, 0.95, sin(uCamPos.w * 0.8 - thick * 2.0) * 0.5 + 0.5) * smoothstep(1.8, 0.3, thick) * energy : 0.0;',
    '  float rapids = vType == 3 ? smoothstep(1.2, 3.5, length(vFlow)) * 0.5 + steep : 0.0;',
    '  float foam = saturate((shore * 0.9 + wave * 0.6 + rapids * 1.2) * smoothstep(0.35, 0.75, foamN + rapids * 0.3));',
    '  foam = max(foam, steep * 0.95);',
    '  // whitecaps where the wave surface folds (low Jacobian) — only in fresh wind',
    '  float cap = smoothstep(0.55, 0.05, gJac) * smoothstep(0.35, 0.9, uWind.z) * smoothstep(0.3, 0.7, foamN + 0.15);',
    '  foam = max(foam, cap * (vType == 1 ? 0.9 : 0.5));',
    '  // churned water behind the player / splashes',
    '  foam = max(foam, smoothstep(0.004, 0.03, gSimV) * 0.55 * smoothstep(0.3, 0.6, foamN));',
    '  vec3 foamC = (sunC * max(uSunDir.y, 0.0) * sh * 0.25 + skyA * 1.1) * 0.9;',
    '  col = mix(col, foamC, foam);',
    '  // ---- fog',
    '  float T = fogTransmittance(uCamPos.xyz, vWorld);',
    '  col = col * T + fogInscatter(vdir) * (1.0 - T);',
    '  if (uCloudMode == 1) { vec4 cl = texture(uCloudTex, suv); col = col * cl.a + cl.rgb; }',
    '  oColor = vec4(col, 0.5);   // a < 0.75 tags water pixels (no depth written) for TAA',
    '}'
  ].join('\n');
})();
